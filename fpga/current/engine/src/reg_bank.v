//=============================================================================
// reg_bank.v —— 运行时寄存器堆（参数从"编译期常量"变成"可写寄存器"）
//
// 【它解锁什么】
//   必须项 M6「单音实时变调」：`inc` 不再是编译期常量，而是可写寄存器。
//   在此之前改一个音高要重新综合整个工程（约 1 分钟）——
//   那不叫乐器，那叫"每次改谱都要重新造琴"。
//
// 【接口为什么长这样】
//   8 位地址 + 8 位数据 + 一个写脉冲。这是刻意选的"最小公约数"：
//     · 仿真里测试台直接驱动三根线就能写
//     · 上板时 UART 收到一个字节就产生一个写脉冲，不需要改这里
//     · 将来换成 CPU/软核，也只是换一个主设备
//   地址空间一次给到 256 字节 —— 改协议格式是牵一发动全身的事，
//   而多留地址几乎不花钱（256×8 = 2048 个触发器，本项目只用了 14%）。
//
// 【地址映射】
//   0x00        CTRL    [0]全局门  [1]包络使能  [3:2]测试模式  [4]静音
//   0x01        MIX     [2:0]增益左移  [4:3]留量右移
//   0x02-0x03   A_INC   起音线性增量（小端 16 位）
//   0x04-0x05   S_LVL   延音电平（小端 16 位）
//   0x06        R_M_K   [4:0]r_k  [6:5]r_m
//   0x07        D_M_K   [4:0]d_k  [6:5]d_m
//   0x08-0x09   CUTOFF  归零阈值（小端 16 位）
//   0x0A-0x0B   D_INC   衰减线性减量
//   0x0C-0x0D   R_INC   释放线性减量
//   0x0E        ENV_MODE[0]指数/线性
//   0x10-0x6F   PITCH   4 声部 × 8 泛音 × 3 字节（小端 24 位）= 96 字节
//                       声部 v、泛音 k → 0x10 + (v*8+k)*3
//   0x70-0x8F   AMP     4 声部 × 8 泛音 × 1 字节 = 32 字节
//   0x90-      保留
//
// 【寄存器不参与复位】
//   复位只清"演奏状态"（相位、包络），不清"参数寄存器"。
//   所以按住复位键再松开，音色与音高不会被弄丢。
//   默认值由 initial 给出 —— 上电即可发声，不需要任何写入。
//=============================================================================

`timescale 1ns/1ps

module reg_bank #(
    parameter AW = 8,       // 地址位宽
    parameter DW = 8,       // 数据位宽
    parameter NW = 256      // 寄存器个数
)(
    input  wire          clk,
    input  wire          rst_n,
    // 写端口
    input  wire          wr_en,
    input  wire [AW-1:0] wr_addr,
    input  wire [DW-1:0] wr_data,
    // 读端口（回读，用于验证"写进去了没有"）
    input  wire          rd_en,
    input  wire [AW-1:0] rd_addr,
    output reg  [DW-1:0] rd_data,
    // 全部寄存器拉平成一根线，由上层切片使用
    output wire [NW*DW-1:0] regs_flat
);

    reg [DW-1:0] mem [0:NW-1];

    //-------------------------------------------------------------------------
    // 上电默认值（Gowin 支持寄存器初值，综合成触发器的 INIT，不额外占资源）
    //-------------------------------------------------------------------------
    integer i;

    //-------------------------------------------------------------------------
    // 只用【字面量赋值】，不用循环 / case / 乘法
    //
    //   曾经写过"循环 + case 选基频 + base*(k+1)"的版本，结果综合失败：
    //   逻辑从 8047 涨到 26226，超过 20736 上限。
    //   原因是综合器没有在展开期把那段循环求值，而是【给它建了硬件】——
    //   相当于凭空塞进几十个乘法器和一大堆选择逻辑。
    //
    //   教训：initial 块里只放常量，别放"看起来像软件"的循环与运算。
    //   展开成字面量虽然啰嗦（142 行），但资源是确定的。
    //-------------------------------------------------------------------------
    //-------------------------------------------------------------------------
    // v1.0 冻结默认表（2026-10-03 按 docs/02-技术方案/19-UART协议v1.0草案.md §3 重写）
    //
    //   为什么要重写（复核 A1）：原来这张表是**全并行版**的——
    //     0x00-0x0E 包络参数 / 0x10-0x6F 4 声部×8 泛音 inc / 0x70-0x8F 幅度表
    //   而 TDM 版把 0x30-0x37 读作颤音/滑音/音色、0x40-0x49 读作效果器、
    //   0x50-0x54 读作定序器、0x58-0x5B 读作塑谱 ⇒ **死区与活区物理重叠**
    //   ⇒ "上电状态从未被定义过"，而且**新功能一读遗留字节就中招** ：
    //     实测 0x5B 的遗留值是并行版的紧凑泛音表，其中 3 位恰为 1
    //     ⇒ 被当成"右手摸到 3 根电极" ⇒ 3 个泛音被 boost ⇒ 闸口 E3 只匹配 13/16
    //
    //   规则（冻结条款 §5.2）：**死区一律清零**并注明"v1.0 冻结保留"
    //   注：并行版（osc_additive_top）也读这张表 ⇒ 它的**上电音色**会随之改变
    //       但那只是参考实现 ；R0 黄金参考**不经过 reg_bank**（测试台直驱引擎）不受影响
    //-------------------------------------------------------------------------
    initial begin
        for (i = 0; i < NW; i = i + 1)
            mem[i] = 8'h00;

        // === 0x00 CTRL（A4：以实现为准）[0]测试 [1]VIB_EN [2]GLIDE_EN [3]preset_src ===
        mem[8'h00] = 8'h02;   // 默认 0x02；VIB/GLIDE 深度步长默认 0 ⇒ inert

        // === 0x01-0x0E：v1.0 冻结保留（原并行版包络参数，全部清零）===
        //     包络全局量当前走编译期常量；将来参数化时在此回归（19 号 §3）

        // === 0x0F RD_REQ（A3 回读触发，写即触发，无默认值）===

        // === 0x30-0x37 表情调制与音色（19 号 §3）===
        mem[8'h37] = 8'h00;   // PRESET = 0（修正：原来遗留值是并行版 inc 表的字节）

        // === 0x40-0x49 效果器 ===
        mem[8'h40] = 8'h01;   // FX_CTRL：仅干声
        mem[8'h41] = 8'hDC;   // DELAY_LEN = 1500（低字节）
        mem[8'h42] = 8'h05;   //            （高字节）A5：必须 < 2^AW=2048
        mem[8'h43] = 8'h60;   // FEEDBACK = 0.375
        mem[8'h44] = 8'hAE;   // CHORUS_RATE = 430（低）
        mem[8'h45] = 8'h01;   //              （高）
        mem[8'h46] = 8'h40;   // CHORUS_DEPTH = 64（低）
        mem[8'h47] = 8'h00;   //               （高）
        mem[8'h48] = 8'h80;   // RV_FB = 0.5 (本次)：0.75 会让线缓冲饱和（实测 91.9% 样本削顶）
        mem[8'h49] = 8'h03;   // RV_DAMP = 3

        // === 0x4A-0x4F 混响扩展保留（T60 档/预延迟）===

        // === 0x50-0x54 定序器 ===
        mem[8'h51] = 8'h7C;   // TEMPO = 636 ≈ 120 BPM（低）
        mem[8'h52] = 8'h02;   //        （中）
        mem[8'h53] = 8'h00;   //        （高）
        mem[8'h54] = 8'h80;   // SEQ_VEL = 128

        // === 0x55-0x57 保留 / 0x58-0x5C 塑谱与亮度轴 ===
        mem[8'h5A] = 8'h02;   // SPEC_MODE：bit0=0 叠加（上电有声）、bit1=1 自动刷新
        // 0x58 SPEC_IDX / 0x59 SPEC_VAL / 0x5B HARM_PADS 默认 0
        //   0x5B 尤其重要：它原来是并行版表里的字节，有 3 位为 1 （见上方说明）
        //
        // 0x5C TILT（独立亮度轴，2026-10-06 落地）默认必须是 **0x70，不是 0**！
        //   表 tilt_wtab.hex 把"恒等"放在档位 7（0x70）；0x00 是【最暗】。
        //   若默认写 0，上电音色就会被这一维改掉，既有全部音频证据失效。
        //   ——这是"新寄存器默认值"最容易被漏掉的一处，故在此显式登记。
        mem[8'h5C] = 8'h70;   // = 档位 7 ⇒ w(k) ≡ 256 ∀k ⇒ 逐位恒等

        // === 0x5D-0x5F 双段衰减（2026-10-23 新增）===
        //   0x5D/0x5E = D2_LVL 16 位小端（Q1.15 断点）
        //   0x5F[4:0] = D2_K 第二段右移量，**0 = 关闭**
        //
        //   默认必须是 0（关闭）。打开会改变所有既有音色的听感，
        //   而"与改动前逐位一致"是全部历史回归判据的前提。
        //   理由与 0x38 的 artic_enable=0、0x6F 的"默认值要显式登记"同源。
        //
        //   注意：0x5D–0x5F 落在 0x10-0x6F 那段"被综合器推成 RAM、
        //   initial 被丢弃"的区间里（见引导序列处的实测记录），
        //   所以这里写 0 只是为了让 DEFAULTS 与引导一致、静态检查不报冲突；
        //   真正的确定性来自 tdm_top_owned.v 引导序列的 6'd54/55/56 三拍。
        //   （0x5D/0x5E/0x5F 默认 0 ⇒ 与 mem 初值一致，无需赋值。）

        // === 0x60-0x61 左手串行事件（写入即触发，默认 0）===

        // === 0x38-0x3F 激发模式（strike / hybrid），2026-10-23 新增 ===
        //   53 位有效，分 8 个字节（位分配见 tdm_top_owned.v 的
        //   "激发模式寄存器组"一节，与 ARTICULATION-RUNTIME-SPEC-20261022 §5.3
        //   的 A6 短命令负载逐字节对齐）。
        //
        //   ★ artic_enable 必须是 0：规格 §3.3 把 sustain 定义为 enable=0，
        //     并且验收第 1 条要求"enable=0 时逐位等价于改动前"。
        //     上电即 strike 会把既有全部音频证据改掉。
        //   ★ 其余字段给推荐值，这样主机只写 0x38=0x23 就能直接听到 strike，
        //     不必先配 8 个字节。
        //
        //   这 8 个字节与 reg_bank_compact.v 的 DEFAULTS 必须一致 ——
        //   那个常量由 tools/gen_compact_defaults.py 从**本表**生成，
        //   改这里之后跑一次生成器即可，不要手改 DEFAULTS。
        mem[8'h38] = 8'h22;   // enable=0 / auto_rel=1 / s_lvl=2
        mem[8'h39] = 8'hFF;   // artic_mask[7:0]
        mem[8'h3A] = 8'hFF;   // artic_mask[15:8]  ⇒ 0xFFFF（全 strike）
        mem[8'h3B] = 8'h2B;   // d_m=3 / d_k_curve=10
        mem[8'h3C] = 8'h0E;   // d_k_base=14
        mem[8'h3D] = 8'hFE;   // hold_ticks[7:0]    79102 = 0x0134FE ⇒ 1500 ms
        mem[8'h3E] = 8'h34;   // hold_ticks[15:8]
        mem[8'h3F] = 8'h01;   // hold_ticks[19:16]

        // === 0x6E VEL_SENS（力度→音色灵敏度，2026-10-23 补默认值）===
        //   **这是一个"寄存器有读取方但从未登记初值"的缺口**：
        //     tdm_top_owned.v:687  r_vel_sens = R[8'h6E*8 +: 8]
        //     tdm_top_owned.v:688  vel_vscale = (r_vel_sens==0) ? 0 : ...   ← 默认值落在"关"
        //   ⇒ 上电后 vel_shape 的 vscale=0 ⇒ 输出恒等于输入 ⇒
        //     **vel_wtab.hex 那 16×16 张表完全没被用上，力度不影响音色**。
        //   这不是表错了（表本身完全符合钢琴行为），是这一维根本没打开。
        //
        //   0x80 = 中区 ⇒ vscale=256 ⇒ 表一等一（逐位还原 vel_wtab 的设计意图）。
        //   档位语义（tdm_top_owned.v:688-691）：
        //     0x00       → 0   关（保留给"我想要固定音色"的场景）
        //     0x01-0x3F  → 128 半灵敏
        //     0x40-0xBF  → 256 一等一   ← 默认落在这里
        //     0xC0-0xFF  → 511 加倍
        //   选 256 而不是 511：511 会把高次泛音的偏差放大 2 倍，
        //   在 vel15 上容易把 k13-k15 推到削顶；256 是表的设计点。
        mem[8'h6E] = 8'h80;   // = 中区 ⇒ vscale 256 ⇒ 力度表一等一

        // === 0x6F VEL_SHIFT（力度量程，2026-10-23 新增）===
        //   pad_scan 里 ev_vel = clamp((raw-base) >> VEL_SHIFT, 0, 15)。
        //   默认 5 是**估计值**（对应未触摸基线 base≈500 拍量级）。
        //   真实值必须上板量：读 pad 遥测看 base 落在哪个量级再反推。
        //   若保持 0 ⇒ 不移位 ⇒ (raw-base) 直接钳到 15 ⇒ 力度只有 0/15 两档，
        //   所以这个默认值不能留 0，必须显式给 5。
        mem[8'h6F] = 8'h05;   // = 5 ⇒ 每档 32 拍

        // === 0x63 SPEC_REFRESH / 0x70-0x73 曲谱下载（无默认值）===

        // === 0x74-0x7E 曲谱扩展保留 ===

        // === 0x7F 协议版本（只读语义；上位机读它识别 v1.0）===
        mem[8'h7F] = 8'h11;   // = 17 ⇒ v1.1：曲谱长度复位与完整谱事务

        // === 0x80-0xFF E8 录音回传缓冲（只读语义，默认 0）===
    end

    //-------------------------------------------------------------------------
    // 写：不参与复位 —— 寄存器是"参数"，不该被演奏复位清掉
    //-------------------------------------------------------------------------
    always @(posedge clk) begin
        if (wr_en && (wr_addr < NW))
            // 协议地址表只覆盖 0x00-0x7F（NW=128）。这里显式忽略 bit7 的写入：
            //   · 板上与仿真行为一致（都忽略），而不是让 0x80-0xFF 别名写入 0x00-0x7F
            //   · 主机若误写 0x80 及以上，不会污染 CTRL 等低地址寄存器
            // 索引固定取低 7 位：NW 恒为 128，且 Gowin 对越界索引会报 EX3784。
            mem[wr_addr[6:0]] <= wr_data;
    end

    //-------------------------------------------------------------------------
    // 读（同步读，一拍出数）
    //-------------------------------------------------------------------------
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n)
            rd_data <= {DW{1'b0}};
        else if (rd_en)
            rd_data <= mem[rd_addr];
    end

    //-------------------------------------------------------------------------
    // 拉平输出
    //-------------------------------------------------------------------------
    genvar g;
    generate
        for (g = 0; g < NW; g = g + 1) begin : G_FLAT
            assign regs_flat[g*DW +: DW] = mem[g];
        end
    endgenerate

endmodule
