//=============================================================================
// vel_shape.v -- 力度 -> 谱形（音色）单元
//
// 依据（见《32-演奏表情问题总表》D-19/D-20 与真乐器物理）：
//   · 力度改变音色的第一性模型是【频谱倾斜】：
//       击得越重 -> 激励脉冲越窄 -> 高频越强
//   · 力度还改变【有几条泛音】：
//       低力度时高次泛音落到门限之下，等于不存在
//     本模块把两者合成一个操作：先取查表权重，再把低于门限的置零。
//
// 权重来源（2026-10-06 最终形态）：**查表**，不是公式
//     w = vel_wtab[vel][part]            （16 档 × 16 条泛音，9 位，256 = 1.0 倍）
//     amp = clamp(base × clamp(w,0..511) >> 8, 0..255)
//   参数只影响"强度"，不影响"形状"：
//     vscale = 0 → w ≡ 256（关）/ 256 → 与表逐位相同 / 511 → 偏差约 2 倍
//
// 三条硬约束（对应判据 V1/V2）：
//   · 基音（part=0）任何力度下都不置零
//   · 最少保留 3 条泛音
//   · 任何参数下 base == 0 ⇒ amp == 0（"没有的泛音"不会被凭空造出来）
//
// 注：tilt_bias / tilt_gain 两个端口是历史接口（当初的公式实现用它们做
//   倾斜偏置与斜率）。改成查表之后，"倾斜"已经烧进表里，这两个量不再
//   参与运算。保留端口是为了不动 tdm_top 的接线与已有测试台；
//   若将来要用它们做全局倾斜，要连同本文件的注释一起更新。
//=============================================================================
module vel_shape #(
    parameter AW    = 8,
    parameter NFLOOR = 9'd64,       // 保护区最小权重（保证基音/低次永不消失）
    parameter NPART_PROTECT = 4'd3  // 前 N 条恒保留
)(
    vel, slot, part, base, tilt_bias, tilt_gain, vscale, amp
);
    input  wire [3:0]         vel;         // 力度 0..15
    input  wire [1:0]         slot;        // 乐器槽 0..3（每层一份表；见下方 2026-10-23 段）
    input  wire [3:0]         part;        // 泛音序号 0..15（0 = 基音）
    input  wire [AW-1:0]      base;        // 该泛音的预设幅度
    input  wire signed [9:0]  tilt_bias;   // 预留（tilt_wtab 已吸收"倾斜"，暂不参与运算）
    input  wire [7:0]         tilt_gain;   // 预留（同上；开关语义已由 vscale 承担）
    input  wire [8:0]         vscale;      // 力度灵敏度（Q0.8）：256 = 与表一等一，0 = 关，511 = 约 2 倍
    output wire [AW-1:0]      amp;

    //=========================================================================
    // 2026-10-06：由【公式】改为【查表】
    //
    //   为什么换：
    //     · 表达力：公式只能表达"倾斜 + 门限置零"；表可以直接写任意谱形
    //       （奇次优先的单簧管式空洞、弱音器的凹陷，都能写进去）
    //     · 时序：原公式含 wmul/15 除法，实测把 SETUP slack 打到 +4.488 ns
    //       （低于 5 ns 阈值，被闸口判红）；查表只剩"ROM + 一次小乘法"
    //     · 可调：表是 hex 文件（tools/scripts/gen_vel_wtab.py 生成），
    //       改音色不用改 RTL
    //
    //   恒等保证：tilt_gain = 0 ⇒ 功能关闭 ⇒ 权重恒为 256 ⇒ amp == base
    //     与改造前逐位相同（判据 V8 守着这一条）。
    //=========================================================================
    //   位宽必须是 12：hex 每项 3 个十六进制位（如 100 / 1D2）。
    //   2026-10-06 实测教训：原先声明 9 位，综合报
    //     WARN (EX2526): Entry size 12 ... does not match memory width 9
    //   仿真侧看不出来（iverilog 按数值读），但【板上 ROM 会装不进去】——
    //   典型的"仿真绿、上板不响"。这里按 12 位声明，只用低 9 位参与计算。
    //
    //   ★ 2026-10-23（四槽分层 刀1）：表从 256 项扩到 1024 项
    //     地址由 {vel,part} 扩为 {slot,vel,part} ⇒ 每个乐器槽可以有自己的
    //     力度→谱形曲线。这是"四层像四种乐器"的前提：钢琴轻按变暗、弦乐
    //     轻按几乎不变，同一张表伺候不了两种。
    //
    //     为什么先扩表再分化内容（两步走，不是一步到位）：
    //       hex 现在写的是【同一张表复制 4 份】⇒ slot 取任何值输出都逐位相同
    //       ⇒ 本刀可以先独立证明"扩地址不改变任何行为"，再单独改表内容。
    //       若一步同时改 RTL 和表，出问题时无法判断是地址接错还是表写错。
    //
    //     成本实测（build_decay2_v1）：BSRAM 15/46，余量 31 块；
    //       1024×12 = 12288 bit < 1 块 18Kbit ⇒ 约 +1 BSRAM，LUT 增量≈0。
    //       原 256×12 = 3072 bit 是靠 SSRAM(RAM16) 分散实现的，扩 4 倍后
    //       综合器会改推成 BSRAM（这是好事，省 CLS）。
    //
    //     不变性守卫：tb_vel_shape 的 E 组判据要求 slot=0/1/2/3 四个取值
    //       下 amp 逐位相同。表一分化，这条判据就会红 —— 那时必须同步
    //       更新判据并说明理由，不能直接删掉它。
    //=========================================================================
    reg [11:0] wtab [0:1023];
    initial $readmemh("vel_wtab.hex", wtab);

    wire [9:0]  widx    = {2'd0, vel, part};
    wire [8:0]  w_rom   = wtab[widx][8:0];             // 异步读：无延迟，无需流水对齐

    //=========================================================================
    // 2026-10-06（第二次改造）：加【力度灵敏度】vscale（Q0.8），并去掉旧主开关
    //
    //   为什么需要 vscale：表把"力度->亮度"的【形状】固定死了，运行时只有开/关。
    //     但"弹下去会不会变亮"是手感问题，必须能在演奏中调 —— 而且
    //     不同音色对灵敏度的要求不一样（钟类音色过灵敏会变刺）。
    //   做法：只缩放【相对恒等的偏差】，不缩放恒等本身：
    //       dw   = wtab[vel][part] - 256           (表想偏离恒等多少)
    //       dw_s = (dw × vscale) >> 8              (按灵敏度缩放)
    //       w    = 256 + dw_s
    //   性质：
    //     vscale = 256 ⇒ dw_s == dw ⇒ w == w_rom ⇒ 与"只用表"逐位相同
    //     vscale = 0   ⇒ w == 256  ⇒ amp == base ⇒ 与"没有这个功能"等价
    //     所以【开关与灵敏度是同一个量】：0 = 关，不需要第二个开关。
    //   为什么不是 (w × vscale) >> 8：那会把恒等也一起缩放，
    //     vscale=128 时整体音量掉一半 —— 那是音量旋钮，不是灵敏度。
    //
    //   ★ 实测教训（2026-10-06）：原实现另有一个 feat_on = (tilt_gain != 0)
    //     总开关，而 tilt_gain(0x6D) 换成查表后**已不参与任何运算**。
    //     后果是"写了灵敏度寄存器 0x6E 却什么都不发生"，集成测试里两支频谱
    //     逐位相同；排查一圈才发现是这个死门。已删除：真正的开关只有 vscale。
    //     （tilt_bias / tilt_gain 两个端口保留但暂不参与运算，见模块头说明。）
    //=========================================================================
    wire signed [9:0]  dw      = $signed({1'b0, w_rom}) - 10'sd256;
    wire signed [17:0] dw_mul  = dw * $signed({1'b0, vscale});
    wire signed [8:0]  dw_sc   = dw_mul[16:8];
    wire signed [9:0]  w_sum   = dw_sc + 10'sd256;
    wire [8:0]         w_raw   = (w_sum[9] == 1'b1)                  ? 9'd0   :
                                 (w_sum > $signed(10'sd511))         ? 9'd511 :
                                                                      w_sum[8:0];

    //   保护区再兜一层：即使表里把基音/低次写得很低，也保底不消失。
    wire        protect = (part == 4'd0) || (part < NPART_PROTECT);
    wire [8:0]  w       = (protect && (w_raw < NFLOOR)) ? NFLOOR : w_raw;

    wire [AW+8:0] shaped_full = base * w;
    assign amp = (shaped_full[AW+8:8] > {AW{1'b1}}) ? {AW{1'b1}} : shaped_full[AW+7:8];

endmodule
