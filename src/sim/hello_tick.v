//=============================================================================
// hello_tick.v —— 分频使能脉冲发生器（仿真入门例子）
//-----------------------------------------------------------------------------
// 【为什么拿它当第一个例子】
//   这个模块是你验收清单里的 B3（"计数器产生每 N 个时钟来一次的使能脉冲"），
//   同时它还是：
//     · UART 波特率发生器的内核
//     · I2S 位时钟（BCK）发生器的内核
//     · 音频采样率发生器（46875 Hz）的内核
//   —— 也就是说，**学会它，你就有了一把万能钥匙**。
//
// 【设计要点：为什么用"使能脉冲"而不是"分频时钟"】
//   很多人第一反应是"把时钟分频，产生一个慢时钟去驱动别的模块"。
//   这在 FPGA 里是**坏习惯**，原因是：
//     · 多出来的时钟要走全局时钟网络（资源有限）
//     · 两个时钟域之间要处理跨时钟域问题（复杂、易错）
//     · 时序分析要对每个时钟分别做
//   正确做法是：**只有一路时钟（clk），用 tick 脉冲当"使能"**，
//   别的模块写成 if (tick) ... 的形式。
//   —— 全设计单时钟域，这是本项目的铁律。
//=============================================================================

`timescale 1ns / 1ps      // 与 testbench 保持一致，避免 iverilog -Wall 报
                          // "timescale inherited from another file" 告警
                          // （Gowin 综合会忽略这一行，不影响码流）

module hello_tick #(
    parameter DIV = 10          // 多少个时钟出一个 tick
)(
    input  wire clk,            // 时钟
    input  wire rst_n,          // 同步复位，低有效
    output reg  tick            // 每 DIV 个时钟拉高 1 拍
);

    // 计到 DIV-1 就够了，所以位宽按能装下 DIV-1 来算。
    // 这里为了简单固定 16 位（够到 65535）；实际项目里可以用 $clog2 精确算。
    reg [15:0] cnt;

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            cnt  <= 16'd0;
            tick <= 1'b0;
        end
        else if (cnt == DIV[15:0] - 16'd1) begin
            // 数满了：归零，并且这一拍 tick 拉高
            cnt  <= 16'd0;
            tick <= 1'b1;
        end
        else begin
            cnt  <= cnt + 16'd1;
            tick <= 1'b0;       // 注意：tick 只高 1 拍，下拍必须落回去
        end
    end

endmodule
