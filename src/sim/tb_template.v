//=============================================================================
// tb_template.v —— Testbench 模板（复制这个文件改名，然后填你的模块）
//-----------------------------------------------------------------------------
// 运行：
//     tools\scripts\sim.cmd  src\sim\tb_你的模块.v  src\rtl\你的模块.v
//
// 【Testbench 是什么】
//   它**不需要能综合成电路**。它是写给仿真器看的一段"剧本"：
//   什么时候给时钟、什么时候给输入、跑到什么时候停、把哪些信号录下来。
//
// 【三个必须有的部分（少一个都会出问题）】
//   1. 时钟      —— 没有时钟，时序逻辑根本不动作
//   2. 激励      —— initial 块里按时间给输入 + 最后必须 $finish
//   3. 波形录制  —— $dumpfile/$dumpvars，不写的话 GTKWave 打开是空白
//
// 【两个高手习惯（建议从一开始就养成）】
//   · 自检：让仿真器打印 PASS/FAIL，而不是每次都用眼睛看波形
//   · 检查逻辑走 negedge：避开和被测模块抢同一个时钟沿的竞争问题
//=============================================================================

`timescale 1ns / 1ps

module tb_template;          // ← 改成 tb_你的模块名

    localparam CLK_PERIOD = 20;      // 20ns = 50MHz

    //-------------------------------------------------------------------------
    // 一、信号声明
    //     被测模块的 input → reg ；被测模块的 output → wire
    //     口诀：我要"驱动"的用 reg，我要"观察"的用 wire
    //-------------------------------------------------------------------------
    reg  clk;
    reg  rst_n;
    reg  [7:0] data_in;         // ← 按你的模块改
    wire [7:0] data_out;        // ← 按你的模块改

    //-------------------------------------------------------------------------
    // 二、时钟
    //-------------------------------------------------------------------------
    initial clk = 1'b0;
    always #(CLK_PERIOD/2) clk = ~clk;

    //-------------------------------------------------------------------------
    // 三、例化被测模块（DUT = Device Under Test）
    //-------------------------------------------------------------------------
    my_design u_dut (            // ← 改成你的模块名
        .clk      (clk),
        .rst_n    (rst_n),
        .data_in  (data_in),
        .data_out (data_out)
    );

    //-------------------------------------------------------------------------
    // 四、录波形
    //-------------------------------------------------------------------------
    initial begin
        $dumpfile("wave.vcd");
        $dumpvars(0, tb_template);       // 0 = 本模块下所有层次都录
    end

    //-------------------------------------------------------------------------
    // 五、自检（可选，但强烈建议）
    //     走 negedge 是为了避开竞争：被测模块在 posedge 更新，
    //     我在 negedge 检查，中间隔半拍，值一定稳定。
    //-------------------------------------------------------------------------
    integer errors;

    always @(negedge clk) begin
        // 在这里写你的断言，例如：
        // if (data_out !== expected) begin
        //     $display("  [FAIL] ...");
        //     errors = errors + 1;
        // end
    end

    //-------------------------------------------------------------------------
    // 六、激励序列
    //-------------------------------------------------------------------------
    initial begin
        errors  = 0;

        // --- 初始化所有输入 ---
        rst_n   = 1'b0;
        data_in = 8'd0;

        // --- 复位 ---
        #(CLK_PERIOD * 3);
        rst_n = 1'b1;
        #(CLK_PERIOD * 2);

        // --- 在这里给激励 ---
        // data_in = 8'hA5;  #(CLK_PERIOD);
        // data_in = 8'h5A;  #(CLK_PERIOD);

        // --- 收尾 ---
        #(CLK_PERIOD * 100);
        $display("");
        if (errors == 0) $display("  [PASS]");
        else             $display("  [FAILED] %0d error(s)", errors);
        $display("");
        $finish;
    end

endmodule
