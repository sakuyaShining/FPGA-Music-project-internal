//=============================================================================
// tb_hello_tick.v —— hello_tick 的 Testbench（**自检式**）
//-----------------------------------------------------------------------------
// 运行：
//     tools\scripts\sim.cmd  src\sim\tb_hello_tick.v src\sim\hello_tick.v
//
// 【这个 testbench 想教你的核心观念】
//
//   仿真有两种用法，**第二种才是专业做法**：
//
//   ① 看波形：把 VCD 录下来，用 GTKWave 用眼睛看
//      → 适合第一次接触、或者调试想不通的问题
//
//   ② 自检（self-checking）：让**仿真器替你判断对错**，
//      跑完直接打印 PASS / FAIL
//      → 几百个用例、每次改代码都要跑，眼睛看不过来
//
//   本文件两种都做：既录波形，又有自动断言。
//   你以后写每个模块的 testbench，都应该有这个"自动判断"的部分。
//
// 【⚠️ 一个必须知道的坑：竞争（race）】
//   被测模块的 tick 和本文件的检查逻辑**都在 clk 上升沿动作**。
//   如果在同一个上升沿读 tick，读到的是"更新前"还是"更新后"的值
//   —— Verilog 标准没有保证，会出随机错误。
//
//   本项目采用的解法：**检查逻辑走 negedge（下降沿）**。
//   上升沿更新、下降沿检查，中间隔了半个周期，值一定已经稳定。
//   这是 testbench 里最简单可靠的避坑手法。
//=============================================================================

`timescale 1ns / 1ps      // 时间单位 1ns，精度 1ps

module tb_hello_tick;

    //-------------------------------------------------------------------------
    // 参数（和被测模块保持一致）
    //-------------------------------------------------------------------------
    localparam DIV        = 10;    // 每 10 个时钟一个 tick
    localparam CLK_PERIOD = 20;    // 时钟周期 20ns = 50MHz

    //-------------------------------------------------------------------------
    // 一、连到被测模块的信号
    //     规则：被测模块的 input → 这里用 reg（我要驱动它）
    //           被测模块的 output → 这里用 wire（我要观察它）
    //-------------------------------------------------------------------------
    reg  clk;
    reg  rst_n;
    wire tick;

    //-------------------------------------------------------------------------
    // 二、时钟发生
    //-------------------------------------------------------------------------
    initial clk = 1'b0;
    always #(CLK_PERIOD/2) clk = ~clk;

    //-------------------------------------------------------------------------
    // 三、例化被测模块（DUT = Device Under Test）
    //-------------------------------------------------------------------------
    hello_tick #(
        .DIV (DIV)
    ) u_dut (
        .clk   (clk),
        .rst_n (rst_n),
        .tick  (tick)
    );

    //-------------------------------------------------------------------------
    // 四、录波形（少了这段，GTKWave 打开是空白窗口）
    //-------------------------------------------------------------------------
    initial begin
        $dumpfile("hello_tick.vcd");
        $dumpvars(0, tb_hello_tick);   // 0 = 本模块下面所有层次都录
    end

    //-------------------------------------------------------------------------
    // 五、自检逻辑
    //     检查内容：相邻两个 tick 之间，是不是**正好**隔了 DIV 个时钟
    //-------------------------------------------------------------------------
    integer cycle;              // 从复位结束算起的时钟数
    integer last_tick_cycle;    // 上一个 tick 出现在第几个时钟
    integer tick_count;
    integer errors;

    always @(negedge clk) begin          // ← 走下降沿，避开竞争（见文件头说明）
        cycle = cycle + 1;

        if (tick) begin
            tick_count = tick_count + 1;

            if (last_tick_cycle >= 0) begin
                if ((cycle - last_tick_cycle) != DIV) begin
                    $display("  [FAIL] tick 间隔 = %0d 拍，应该是 %0d 拍  (第 %0d 拍)",
                             cycle - last_tick_cycle, DIV, cycle);
                    errors = errors + 1;
                end
            end
            last_tick_cycle = cycle;
        end
    end

    //-------------------------------------------------------------------------
    // 六、激励序列
    //-------------------------------------------------------------------------
    initial begin
        cycle           = 0;
        last_tick_cycle = -1;
        tick_count      = 0;
        errors          = 0;

        // --- 复位保持 3 个时钟 ---
        rst_n = 1'b0;
        #(CLK_PERIOD * 3);
        rst_n = 1'b1;

        // --- 放开跑，观察 5 个完整的 tick 周期 ---
        #(CLK_PERIOD * DIV * 5);

        // --- 判定 ---
        $display("");
        if (tick_count < 4) begin
            $display("  [FAIL] 只观察到 %0d 个 tick，太少了（模块可能根本没动）", tick_count);
            errors = errors + 1;
        end

        if (errors == 0)
            $display("  [PASS] 观察到 %0d 个 tick，间隔全部正好 %0d 拍", tick_count, DIV);
        else
            $display("  [FAILED] 共 %0d 处错误", errors);

        $display("");
        $finish;              // 不写这句，仿真会一直跑到超时上限
    end

endmodule
