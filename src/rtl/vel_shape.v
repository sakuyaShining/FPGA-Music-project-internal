//=============================================================================
// vel_shape.v -- 力度 -> 谱形（音色）单元
//
// 依据（见《32-演奏表情问题总表》D-19/D-20 与真乐器物理）：
//   · 力度改变音色的第一性模型是【频谱倾斜】：
//       击得越重 -> 激励脉冲越窄 -> 高频越强
//   · 力度还改变【有几条泛音】：
//       低力度时高次泛音落到门限之下，等于不存在
//     本模块把两者合成一个操作：先算倾斜权重，再把低于门限的置零。
//
// 权重公式（第 0 版，公式实现的"表"；后续调音时可换成 16x16 逐项表）：
//     w(k, v) = 256 + tilt_eff(v) * (2k - 15) / 15        k = 0..15
//     tilt_eff(v) = TILT_BIAS + v * TILT_GAIN             (有符号)
//     amp(k) = base(k) * clamp(w, 0..511) >> 8           若该条被保留
//     amp(k) = 0                                        若 w 低于门限且不在保护区内
//
// 三条硬约束（对应判据 V1/V2）：
//   · 基音（part=0）任何力度下都不置零
//   · 最少保留 3 条泛音
//=============================================================================
module vel_shape #(
    parameter AW    = 8,          // 幅度位宽
    parameter NFLOOR = 8'd24,     // 门限：权重低于它则置零（决定"条数"）
    parameter NPART_PROTECT = 4'd3 // 前 N 条恒保留（含基音）
)(
    vel, part, base, tilt_bias, tilt_gain, amp
);
    input  wire [3:0]         vel;         // 力度 0..15
    input  wire [3:0]         part;        // 泛音序号 0..15（0 = 基音）
    input  wire [AW-1:0]      base;        // 该泛音的预设幅度
    input  wire signed [9:0]  tilt_bias;   // 倾斜偏置（负 = 低力度偏暗）
                                          //   2026-10-05：原为 signed[7:0]，最小 -128，
                                          //   而置零需要 bias < -232 ⇒ 置零路径【不可达】。
                                          //   加宽到 [9:0] 后才真正能压低高次泛音。
    input  wire [7:0]         tilt_gain;   // 每档力度的倾斜增量
    output wire [AW-1:0]      amp;         // 谱形后的幅度（组合输出，零延迟）

    //------------------------------------------------------------------
    // 倾斜量：有符号，随力度线性增长
    //------------------------------------------------------------------
    wire signed [15:0] tilt_eff = $signed({{6{tilt_bias[9]}}, tilt_bias}) +
                                  ($signed({8'd0, tilt_gain}) * $signed({12'd0, vel}));
    //   tilt_gain <= 127、vel <= 15 ⇒ 增量 <= 1905，加上 bias 不会溢出 16 位

    //------------------------------------------------------------------
    // 权重：低次减、高次增（skew = 2k-15 ∈ [-15, +15]）
    //------------------------------------------------------------------
    wire signed [15:0] skew = $signed({12'd0, part}) * 16'sd2 - 16'sd15;
    wire signed [15:0] wmul = tilt_eff * skew;
    wire signed [15:0] wraw = 16'sd256 + (wmul / 16'sd15);   // 截断向零，够用

    wire signed [15:0] wcl  = (wraw < 16'sd0)   ? 16'sd0   :
                              (wraw > 16'sd511) ? 16'sd511 : wraw;

    //------------------------------------------------------------------
    // 保留判定
    //------------------------------------------------------------------
    wire protect  = (part == 4'd0) || (part < NPART_PROTECT);   // 基音 + 前 N 条
    wire above    = (wcl > $signed({8'd0, NFLOOR}));
    wire keep     = protect || above;

    //------------------------------------------------------------------
    // 应用权重（wcl 在 0..511，右移 8 位）
    //------------------------------------------------------------------
    wire [AW+8:0] shaped_full = base * wcl[8:0];
    // 组合输出（零延迟）：调用方（note_map 的装载通路）自己寄存，
    //   这样插入到 amp_src 与"力度乘法"之间不会增加流水级。
    wire [AW-1:0] shaped = (shaped_full[AW+8:8] > {AW{1'b1}})
                           ? {AW{1'b1}}                  // 饱和，不绕回
                           : shaped_full[AW+7:8];

    // 恒等性：tilt_bias=0 且 tilt_gain=0 ⇒ w=256 ⇒ amp == base（逐位相同）
    assign amp = keep ? shaped : {AW{1'b0}};

endmodule
