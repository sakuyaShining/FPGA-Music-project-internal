//=============================================================================
// mixer.v —— 多声部混音器（加法叠加 + 电平增益 + 留量 + 饱和限幅）
//
// 【为什么需要"电平增益"（这是实测发现的问题，不是可选项）】
//   单个泛音的输出是 (sine × amp) >> 8：
//       sine 是 Q1.15（满幅 ±32767），amp 是 0..255
//       → 单个泛音满幅约 ±32639，也就是【Q1.15 量级】
//   8 个泛音相加、4 个声部再相加，最多也就几十万，
//   而 24 bit 满幅是 ±8 388 608 —— 信号只用了量程的【0.6%】，
//   折算到 I2S 的 16 bit 就是约 −44 dBFS：**轻得几乎听不见**。
//
//   所以混音器必须提供增益。默认 +6 bit（×64）：
//       实测 1 声部 8 泛音峰值 49117 → ×64 = 3.14 M ≈ −8.5 dBFS，正常音量。
//   这个增益将来由寄存器映射给出（步骤 6），现场可调。
//
// 【两段式增益：先提升、后留量】
//   scaled = (sum << gain_up) >>> shift
//     gain_up : 0..7，把信号提到可用量程
//     shift   : 0..3，多声部叠加时留余量，避免持续削顶
//   两者独立的好处：换声部数时只动 shift，不动整体音量标定。
//
// 【为什么不用自动增益控制（AGC）】
//   AGC 会让"按一个音"和"按四个音"一样响，力度信息全丢了。
//   宁可让用户手动留量，也不要 AGC。
//
// 【为什么用饱和而不是截断】
//   截断会让超出范围的数值"回绕"成反相，听起来是刺耳的爆音。
//   饱和只是削平顶部，是可控失真（模拟合成器也这么做）。
//=============================================================================

`timescale 1ns/1ps

module mixer #(
    parameter NV = 4,       // 声部数
    parameter IW = 24,      // 每个声部的样本位宽（有符号）
    parameter OW = 24       // 输出样本位宽（有符号）
)(
    input  wire signed [NV*IW-1:0] vin,       // 各声部样本（拼接，低段是 0 号声部）
    input  wire [2:0]              gain_up,   // 电平增益（左移位数 0..7）
    input  wire [1:0]              shift,     // 增益留量（右移位数 0..3）
    output reg  signed [OW-1:0]    vout
);

    // 内部累加器要给足位宽：NV 路相加 + 最多 7 位增益
    localparam AW = IW + 4 + 8;               // 24+4+8 = 36

    reg signed [AW-1:0] acc;
    integer i;

    //   ★ 切片必须显式 $signed()！
    //     Verilog 里对一个向量取切片得到的是【无符号】值，
    //     负数会变成 ~2^24 那么大的正数。实测就是这么错的：
    //     声部输出峰值显示成 16776839（≈ 2^24）而不是 15360。
    always @(*) begin
        acc = {AW{1'b0}};
        for (i = 0; i < NV; i = i + 1)
            acc = acc + $signed(vin[i*IW +: IW]);
    end

    // 先提升电平，再留量
    wire signed [AW-1:0] scaled = (acc <<< gain_up) >>> shift;

    localparam signed [AW-1:0] MAXV =  (1 <<< (OW-1)) - 1;   //  2^(OW-1)-1
    localparam signed [AW-1:0] MINV = -(1 <<< (OW-1));       // -2^(OW-1)

    always @(*) begin
        if (scaled > MAXV)
            vout = MAXV[OW-1:0];
        else if (scaled < MINV)
            vout = MINV[OW-1:0];
        else
            vout = scaled[OW-1:0];
    end

endmodule
