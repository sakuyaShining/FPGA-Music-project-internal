//=============================================================================
// reg_bank.v —— 运行时寄存器堆（参数从"编译期常量"变成"可写寄存器"）
//
// 【它解锁什么】
//   必须项 M6「单音实时变调」：`inc` 不再是编译期常量，而是可写寄存器。
//   在此之前改一个音高要重新综合整个工程（约 1 分钟）——
//   那不叫乐器，那叫"每次改谱都要重新造琴"。
//
// 【接口为什么长这样】
//   8 位地址 + 8 位数据 + 一个写脉冲。这是刻意选的"最小公约数"：
//     · 仿真里测试台直接驱动三根线就能写
//     · 上板时 UART 收到一个字节就产生一个写脉冲，不需要改这里
//     · 将来换成 CPU/软核，也只是换一个主设备
//   地址空间一次给到 256 字节 —— 改协议格式是牵一发动全身的事，
//   而多留地址几乎不花钱（256×8 = 2048 个触发器，本项目只用了 14%）。
//
// 【地址映射】
//   0x00        CTRL    [0]全局门  [1]包络使能  [3:2]测试模式  [4]静音
//   0x01        MIX     [2:0]增益左移  [4:3]留量右移
//   0x02-0x03   A_INC   起音线性增量（小端 16 位）
//   0x04-0x05   S_LVL   延音电平（小端 16 位）
//   0x06        R_M_K   [4:0]r_k  [6:5]r_m
//   0x07        D_M_K   [4:0]d_k  [6:5]d_m
//   0x08-0x09   CUTOFF  归零阈值（小端 16 位）
//   0x0A-0x0B   D_INC   衰减线性减量
//   0x0C-0x0D   R_INC   释放线性减量
//   0x0E        ENV_MODE[0]指数/线性
//   0x10-0x6F   PITCH   4 声部 × 8 泛音 × 3 字节（小端 24 位）= 96 字节
//                       声部 v、泛音 k → 0x10 + (v*8+k)*3
//   0x70-0x8F   AMP     4 声部 × 8 泛音 × 1 字节 = 32 字节
//   0x90-      保留
//
// 【寄存器不参与复位】
//   复位只清"演奏状态"（相位、包络），不清"参数寄存器"。
//   所以按住复位键再松开，音色与音高不会被弄丢。
//   默认值由 initial 给出 —— 上电即可发声，不需要任何写入。
//=============================================================================

`timescale 1ns/1ps

module reg_bank #(
    parameter AW = 8,       // 地址位宽
    parameter DW = 8,       // 数据位宽
    parameter NW = 256      // 寄存器个数
)(
    input  wire          clk,
    input  wire          rst_n,
    // 写端口
    input  wire          wr_en,
    input  wire [AW-1:0] wr_addr,
    input  wire [DW-1:0] wr_data,
    // 读端口（回读，用于验证"写进去了没有"）
    input  wire          rd_en,
    input  wire [AW-1:0] rd_addr,
    output reg  [DW-1:0] rd_data,
    // 全部寄存器拉平成一根线，由上层切片使用
    output wire [NW*DW-1:0] regs_flat
);

    reg [DW-1:0] mem [0:NW-1];

    //-------------------------------------------------------------------------
    // 上电默认值（Gowin 支持寄存器初值，综合成触发器的 INIT，不额外占资源）
    //-------------------------------------------------------------------------
    integer i;

    //-------------------------------------------------------------------------
    // 只用【字面量赋值】，不用循环 / case / 乘法
    //
    //   曾经写过"循环 + case 选基频 + base*(k+1)"的版本，结果综合失败：
    //   逻辑从 8047 涨到 26226，超过 20736 上限。
    //   原因是综合器没有在展开期把那段循环求值，而是【给它建了硬件】——
    //   相当于凭空塞进几十个乘法器和一大堆选择逻辑。
    //
    //   教训：initial 块里只放常量，别放"看起来像软件"的循环与运算。
    //   展开成字面量虽然啰嗦（142 行），但资源是确定的。
    //-------------------------------------------------------------------------
    //-------------------------------------------------------------------------
    // v1.0 冻结默认表（2026-10-03 按 docs/02-技术方案/19-UART协议v1.0草案.md §3 重写）
    //
    //   为什么要重写（复核 A1）：原来这张表是**全并行版**的——
    //     0x00-0x0E 包络参数 / 0x10-0x6F 4 声部×8 泛音 inc / 0x70-0x8F 幅度表
    //   而 TDM 版把 0x30-0x37 读作颤音/滑音/音色、0x40-0x49 读作效果器、
    //   0x50-0x54 读作定序器、0x58-0x5B 读作塑谱 ⇒ **死区与活区物理重叠**
    //   ⇒ "上电状态从未被定义过"，而且**新功能一读遗留字节就中招** ：
    //     实测 0x5B 的遗留值是并行版的紧凑泛音表，其中 3 位恰为 1
    //     ⇒ 被当成"右手摸到 3 根电极" ⇒ 3 个泛音被 boost ⇒ 闸口 E3 只匹配 13/16
    //
    //   规则（冻结条款 §5.2）：**死区一律清零**并注明"v1.0 冻结保留"
    //   注：并行版（osc_additive_top）也读这张表 ⇒ 它的**上电音色**会随之改变
    //       但那只是参考实现 ；R0 黄金参考**不经过 reg_bank**（测试台直驱引擎）不受影响
    //-------------------------------------------------------------------------
    initial begin
        for (i = 0; i < NW; i = i + 1)
            mem[i] = 8'h00;

        // === 0x00 CTRL（A4：以实现为准）[0]测试 [1]VIB_EN [2]GLIDE_EN [3]preset_src ===
        mem[8'h00] = 8'h02;   // 默认 0x02；VIB/GLIDE 深度步长默认 0 ⇒ inert

        // === 0x01-0x0E：v1.0 冻结保留（原并行版包络参数，全部清零）===
        //     包络全局量当前走编译期常量；将来参数化时在此回归（19 号 §3）

        // === 0x0F RD_REQ（A3 回读触发，写即触发，无默认值）===

        // === 0x30-0x37 表情调制与音色（19 号 §3）===
        mem[8'h37] = 8'h00;   // PRESET = 0（修正：原来遗留值是并行版 inc 表的字节）

        // === 0x40-0x49 效果器 ===
        mem[8'h40] = 8'h01;   // FX_CTRL：仅干声
        mem[8'h41] = 8'hDC;   // DELAY_LEN = 1500（低字节）
        mem[8'h42] = 8'h05;   //            （高字节）A5：必须 < 2^AW=2048
        mem[8'h43] = 8'h60;   // FEEDBACK = 0.375
        mem[8'h44] = 8'hAE;   // CHORUS_RATE = 430（低）
        mem[8'h45] = 8'h01;   //              （高）
        mem[8'h46] = 8'h40;   // CHORUS_DEPTH = 64（低）
        mem[8'h47] = 8'h00;   //               （高）
        mem[8'h48] = 8'h80;   // RV_FB = 0.5 (本次)：0.75 会让线缓冲饱和（实测 91.9% 样本削顶）
        mem[8'h49] = 8'h03;   // RV_DAMP = 3

        // === 0x4A-0x4F 混响扩展保留（T60 档/预延迟）===

        // === 0x50-0x54 定序器 ===
        mem[8'h51] = 8'h7C;   // TEMPO = 636 ≈ 120 BPM（低）
        mem[8'h52] = 8'h02;   //        （中）
        mem[8'h53] = 8'h00;   //        （高）
        mem[8'h54] = 8'h80;   // SEQ_VEL = 128

        // === 0x55-0x57 保留 / 0x58-0x5B 塑谱 ===
        mem[8'h5A] = 8'h02;   // SPEC_MODE：bit0=0 叠加（上电有声）、bit1=1 自动刷新
        // 0x58 SPEC_IDX / 0x59 SPEC_VAL / 0x5B HARM_PADS 默认 0
        //   0x5B 尤其重要：它原来是并行版表里的字节，有 3 位为 1 （见上方说明）

        // === 0x60-0x61 左手串行事件（写入即触发，默认 0）===

        // === 0x63 SPEC_REFRESH / 0x70-0x73 曲谱下载（无默认值）===

        // === 0x74-0x7E 曲谱扩展保留 ===

        // === 0x7F 协议版本（只读语义；上位机读它识别 v1.0）===
        mem[8'h7F] = 8'h10;   // = 16 ⇒ v1.0

        // === 0x80-0xFF E8 录音回传缓冲（只读语义，默认 0）===
    end

    //-------------------------------------------------------------------------
    // 写：不参与复位 —— 寄存器是"参数"，不该被演奏复位清掉
    //-------------------------------------------------------------------------
    always @(posedge clk) begin
        if (wr_en)
            mem[wr_addr] <= wr_data;
    end

    //-------------------------------------------------------------------------
    // 读（同步读，一拍出数）
    //-------------------------------------------------------------------------
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n)
            rd_data <= {DW{1'b0}};
        else if (rd_en)
            rd_data <= mem[rd_addr];
    end

    //-------------------------------------------------------------------------
    // 拉平输出
    //-------------------------------------------------------------------------
    genvar g;
    generate
        for (g = 0; g < NW; g = g + 1) begin : G_FLAT
            assign regs_flat[g*DW +: DW] = mem[g];
        end
    endgenerate

endmodule
