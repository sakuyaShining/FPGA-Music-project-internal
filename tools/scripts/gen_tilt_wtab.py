#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
gen_tilt_wtab.py -- 生成【独立亮度轴】0x5C TILT 的权重表 tilt_wtab.hex

它和 vel_wtab.hex 是两件事，别混：

    vel_wtab.hex   力度 -> 谱形。  索引 = vel*16+part。**演奏中按下多重**决定。
    tilt_wtab.hex  亮度轴 -> 谱形。索引 = tilt 档。    **手在泛音排上滑到哪**决定。

为什么要有独立的表（而不是复用 vel_wtab）：
    规格里"亮度"是第 4 个独立表情维（32 号 D-13）。用户选的形状是
    「倾斜轴为主」：让谱形**变亮**，而不是"变响"。
    —— 逐条等比缩放会变成音量变化，那是被明确否决的做法（32 号 D-13 否决项）。

    ★ 2026-10-07 更正一处与数据不符的描述（原文写"基音退、高次进"）：
      公式 `w(t,k) = 256 + ((t-7)*k*896)//105` 里 k 是**乘数**，
      k=0（基音）时 (t-7)*0 = 0 ⇒ **w(t,0) 恒为 256**，即
      **基音在整条轴上保持不变，只有高次泛音在进**。
      "倾斜"体现在**高低次之间的相对关系变陡**，而不是基音绝对值下降。
      （实测：w(0,15)=0、w(15,15)=511、w(*,0)=256，见下方 selfcheck 的 2b/2c 两条契约。）
      这处更正很重要：照原文措辞写判据会把**正常的表判成失败**（本轮就是这么发现的）。

表结构：16 档（tilt 0..255 量化到 16 档，每档 16 个十六进制步进）
    每项 9 位，256 = 1.0 倍（恒等）
    w(t, k) = 256 + ((t - 7) * k * 896) // 105     k = 0..15（0 = 基音）
    896 = 256 * 3.5，105 = 7 * 15 → 使 t=15, k=15 时 w 正好 511（到顶不溢出）

三条性质（判据 T 系列要验的就是它们）：
    · w(7, k) == 256  ∀k   ⇒ 中点即【恒等】。写入 0x5C=0x70 不改变音色。
    · t=0 时基音被压到 0.5 倍 → 不是静音（"最暗"仍有音高，判据 T3）
    · 基音恒不为 0 ⇒ 亮度推到哪一档都不会把音"变没"
"""
import sys

NZERO = 7            # 中点档 = 恒等（对应寄存器值 0x70 = 112）
K_NUM = 896          # 斜率分子
K_DEN = 105          # 斜率分母（= 7 × 15）


def weight(t, k):
    w = 256 + ((t - NZERO) * k * K_NUM) // K_DEN
    return max(0, min(511, w))


#   规格里 0x5C 的默认值是 0x70 = 112，量化成 16 档就是第 7 档。
#   ★ 这个 7 必须**独立写死**，不能引用 NZERO ——
#     第一版自校验用 NZERO 同时做"公式参数"和"期望值"，
#     于是把 NZERO 改成 8 也能"通过"（它只是换了哪一档算恒等）——
#     那是个**循环判据**，永远绿。真正的契约是**寄存器 0x70 必须恒等**，
#     所以这里按寄存器值独立算一次。
IDENT_T_FROM_REG = (0x70 * 16) // 256     # 0x70=112 -> 112*16/256 = 7


def w_raw(t, k):
    """未截顶的原始值（判据要的是"斜率常数对不对"，不是"截顶后是不是 511"）。
    踩过的坑：只查 `hi == 511` 时，把 K_DEN 从 105 改成 104 也能通过 ——
    因为原始值变成 1289、截顶后**仍然是 511**，看起来没变。
    真正的契约是 t=15,k=15 的原始值**恰好等于 511**（到顶不溢出）。"""
    return 256 + ((t - NZERO) * k * K_NUM) // K_DEN


def selfcheck():
    """生成前自校验三条性质，任一不成立即返回失败。

    为什么必须有（本项目已多次栽在"表不对劲但没人发现"上）：
      · $readmemh 数组开小 ⇒ 静默只装一半、其余 X（note_map.v 踩过）
      · 位域重叠       ⇒ 整表报废（note_map_gen.py 的 ratio/amp/epar 踩过）
      · 缺表            ⇒ 曾被门禁漏过（后由 copy_data() 兜住）
    这些都属于"数据错了但流程照样绿"。所以生成脚本必须**自己先验**，
    而不是假设下游会挡住。
    """
    errs = []

    #   性质 0：公式用的恒等档必须与**寄存器 0x70 量化出来的档**一致。
    #   这一条把"公式内部自洽"与"对上寄存器契约"分开 —— 前者自洽但后者可能错。
    if NZERO != IDENT_T_FROM_REG:
        errs.append("恒等档不一致：公式用 t=%d，而寄存器 0x70 量化应为 t=%d"
                    % (NZERO, IDENT_T_FROM_REG))

    #   性质 1：寄存器默认值那一档必须恒等 —— 写入 0x5C=0x70 不得改变音色。
    #   这一条最关键：默认值就是它，一旦破了，所有既有音频证据全部失效。
    for k in range(16):
        w = weight(IDENT_T_FROM_REG, k)
        if w != 256:
            errs.append("恒等性破坏: w(%d,%d)=%d != 256" % (IDENT_T_FROM_REG, k, w))

    #   性质 2：最暗档基音不为 0（"最暗"仍有音高，见判据 T3）
    if weight(0, 0) == 0:
        errs.append("最暗档基音为 0 ⇒ 会把音变没")

    #   性质 2b：**方向正确** —— 亮度轴往上推时，高次泛音必须变大。
    #   这条才是"亮度轴"的定义本身：倾斜轴让谱形**变亮**，而不是整体变响。
    #   它挡的是"斜率符号写反"这类错误 —— 那会让"变亮"听起来是"变暗"，
    #   而幅度范围 / 恒等性等其它判据**全都察觉不到**。
    w_dark_hi = weight(0, 15)
    w_brt_hi  = weight(15, 15)
    if not (w_brt_hi > w_dark_hi):
        errs.append("方向错误：最亮档高次泛音 %d 未大于最暗档 %d（斜率符号可能反了）"
                    % (w_brt_hi, w_dark_hi))

    #   性质 2c：**基音在整条轴上必须不变**（k=0 时公式退化为 256 + 0）。
    #   ★ 这一条纠正了本文件顶部注释的一处**与数据不符**的描述。
    #     注释原文写「基音退、高次进」，但实测 weight(t, 0) == 256 对所有 t 成立 ——
    #     即**基音保持不变，只有高次泛音在进**。公式里 k 是乘数，k=0 时 (t-7)*0=0。
    #     "倾斜"体现在**高低次之间的相对关系**变陡，而不是基音绝对值下降。
    #     若照注释去断言"最亮档基音 < 最暗档基音"，正常表会**被判失败**（实测就是如此）。
    #     教训同上：注释里的措辞不是契约，必须用实际数据核对后再写成判据。
    for t in range(16):
        if weight(t, 0) != 256:
            errs.append("基音不恒定: w(%d,0)=%d != 256（k=0 时公式应退化为 256）"
                        % (t, weight(t, 0)))
            break

    #   性质 3：**截顶后的**全表必须落在 9 位内（表项位宽必须与 hex 的 3 个十六进制位一致）。
    #
    #   关于"到顶不溢出"（原文的表述，这里刻意**不**做断言）：
    #     实测 w_raw(15,15) = 1280 > 511，是靠 `min(511, ...)` 截回来的。
    #     我一度把它写成"w_raw(15,15) 必须恰好等于 511"，结果**正常的表反被判失败** ——
    #     那是我从文档表述里**臆造**出来的不变量，不是设计契约。
    #     教训：文档里"看起来像不变量"的措辞必须先用实际数据核对，
    #           否则会写出一个**永远红**的假判据，比没有判据更糟 ——
    #           它会逼着后来的人去改本来就对的常数。
    #
    #   同理，K_NUM / K_DEN 的具体数值**不做**断言：它们只决定中间档的过渡快慢，
    #   属"听感调参"而非契约；写死会让正常调参被误判为失败。
    #   本自校验只认**契约**：对得上寄存器恒等档 / 恒等档恒等 / 基音不为 0 /
    #   方向正确 / 落在 9 位内。
    lo, hi = 999, -1
    for t in range(16):
        for k in range(16):
            w = weight(t, k)
            lo = min(lo, w)
            hi = max(hi, w)
            if w < 0 or w > 511:
                errs.append("越界: w(%d,%d)=%d 不在 [0,511]" % (t, k, w))

    return errs, lo, hi


def main():
    errs, lo, hi = selfcheck()
    if errs:
        sys.stderr.write("gen_tilt_wtab: 自校验失败 %d 项：\n" % len(errs))
        for e in errs[:10]:
            sys.stderr.write("  ✗ %s\n" % e)
        return 1

    lines = []
    for t in range(16):
        row = [weight(t, k) for k in range(16)]
        lines.append(" ".join("%03X" % x for x in row))
    sys.stdout.write("\n".join(lines) + "\n")
    #   自校验结论走 stderr，避免污染 stdout 的表数据
    sys.stderr.write("gen_tilt_wtab: 自校验通过（w 范围 %d..%d，恒等档 t=%d）\n"
                     % (lo, hi, NZERO))
    return 0


if __name__ == "__main__":
    sys.exit(main())
