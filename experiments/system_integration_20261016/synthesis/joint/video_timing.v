//=============================================================================
// video_timing.v —— RGB 液晶屏行/场时序发生器（480 × 272）
//-----------------------------------------------------------------------------
// 目标屏：Sipeed 4.3 寸 RGB 屏，480×272，40P 排线
// 像素时钟：9 MHz（来自 gowin_rpll，标称值）
//
// 【一行的结构】hcnt 从 0 数到 H_TOTAL-1，然后归零，同时 vcnt 加一
//
//    hcnt:  0        30                      510   520        560
//           |────────|────────────────────────|─────|──────────|
//           后沿 30    有效像素 480            前沿10  同步脉冲40
//           (blank)   (DE = 1)                (blank) (HSYNC 低)
//
//   一帧（297 行）结构同理：
//    vcnt:  0    5                          277  282      297
//           |────|───────────────────────────|────|────────|
//           后沿5   有效行 272                前沿5  同步15行
//
//   → DE 拉高的范围正好是 480 × 272 个像素，一个不多一个不少。
//
// 【与官方例程的差异，以及为什么敢改】
//   官方 TangNano-9K-example/lcd_4.3 的同步信号生成是：
//       LCD_HSYNC = (hcnt <= 510) ? 0 : 1      // 几乎整行都是低电平
//       LCD_VSYNC = (vcnt <= 297) ? 0 : 1      // 恒等于 0，永远没有脉冲
//   也就是说官方例程实际上**完全没有输出有效的行场同步脉冲**，只靠 DE。
//   它能出货、能点亮，说明这块屏工作在 "DE 模式"（只用 DE 锁存数据，
//   HSYNC/VSYNC 被忽略）。据此可以做一个安全的推断：
//       官方能跑 ⇒ 屏忽略同步信号 ⇒ 本文件输出规范同步脉冲，屏照样忽略 ⇒ 也能跑
//   反过来，万一面板其实需要同步脉冲，那官方的恒 0 根本不可能显示，
//   与"官方能显示"矛盾。所以输出规范脉冲是**不会更差、只会更好**的改动。
//   （本推断的前提是"官方例程确实能点亮该屏"，这一点将由先烧官方 .fs 验证。）
//
// 【单位与位宽】
//   H_TOTAL = 560，V_TOTAL = 297，9 MHz / (560×297) ≈ 54.1 Hz 场频。
//   计数器用 16 位，够到 65535，余量充足。
//=============================================================================

module video_timing #(
    parameter H_ACTIVE = 480,   // 一行有效像素数
    parameter H_BP     = 30,    // 行后沿（有效像素之前）
    parameter H_FP     = 10,    // 行前沿（有效像素之后、同步之前）
    parameter H_SYNC_W = 40,    // 行同步脉冲宽度
    parameter V_ACTIVE = 272,   // 一帧有效行数
    parameter V_BP     = 5,     // 场后沿
    parameter V_FP     = 5,     // 场前沿
    parameter V_SYNC_W = 15     // 场同步脉冲宽度
)(
    input  wire        pix_clk,     // 像素时钟（9 MHz）
    input  wire        rst_n,       // 同步复位，低有效
    output reg         de,          // 数据有效（Data Enable）：高 = 当前像素属于有效画面
    output wire        de_comb,     // 同上，但**组合逻辑**输出，供图案模块使用（见下方说明）
    output reg         hsync,       // 行同步，低有效
    output reg         vsync,       // 场同步，低有效
    output wire [15:0] x,           // 当前像素在一行内的坐标（0 ~ H_TOTAL-1）
    output wire [15:0] y,           // 当前行在一帧内的坐标（0 ~ V_TOTAL-1）
    output reg         frame_tick   // 每帧最后一个像素时拉高 1 拍
);

    //-------------------------------------------------------------------------
    // 行/场总长度（推导出来的常量，不手工写死）
    //-------------------------------------------------------------------------
    localparam H_TOTAL = H_ACTIVE + H_BP + H_FP + H_SYNC_W;  // 480+30+10+40 = 560
    localparam V_TOTAL = V_ACTIVE + V_BP + V_FP + V_SYNC_W;  // 272+5 +5 +15 = 297

    // 同步脉冲在计数器上的起止位置
    //   行：有效像素结束(H_BP+H_ACTIVE) → 前沿(H_FP) → 同步脉冲(H_SYNC_W)
    localparam H_SYNC_BEG = H_BP + H_ACTIVE + H_FP;   // 30+480+10 = 520
    localparam H_SYNC_END = H_SYNC_BEG + H_SYNC_W;    // 520+40   = 560
    localparam V_SYNC_BEG = V_BP + V_ACTIVE + V_FP;   // 5+272+5  = 282
    localparam V_SYNC_END = V_SYNC_BEG + V_SYNC_W;    // 282+15   = 297

    reg [15:0] hcnt;    // 行内像素计数
    reg [15:0] vcnt;    // 帧内行计数

    wire [15:0] hcnt_next = hcnt + 16'd1;
    wire [15:0] vcnt_next = vcnt + 16'd1;

    //-------------------------------------------------------------------------
    // 计数器本体：先数行、数满一行再数帧
    //-------------------------------------------------------------------------
    always @(posedge pix_clk or negedge rst_n) begin
        if (!rst_n) begin
            hcnt <= 16'd0;
            vcnt <= 16'd0;
        end
        else if (hcnt == H_TOTAL[15:0] - 16'd1) begin
            // 一行数完：行计数归零，行号加一（数满一帧则归零）
            hcnt <= 16'd0;
            vcnt <= (vcnt == V_TOTAL[15:0] - 16'd1) ? 16'd0 : vcnt_next;
        end
        else begin
            hcnt <= hcnt_next;
        end
    end

    //-------------------------------------------------------------------------
    // DE 的"当前值"（组合逻辑）
    //
    // 【为什么必须同时提供组合版和寄存版 —— 这是一个真实踩过的坑】
    // 图案模块是这样写的：
    //     颜色是 x/y 的**组合逻辑**（本拍生效） → 再打一拍输出
    // 如果它拿**寄存后的** de 去门控这个组合颜色，那么在同一拍里：
    //     颜色用的是 x(t)   （本拍的坐标）
    //     de  用的是 x(t-1) （上一拍的坐标）
    // 两者相差 1 拍，有效区边缘就会错 1 个像素。
    // 正确做法：图案模块必须用**组合版** de_comb，它和 x/y 是同一拍、同一坐标。
    // 而送给引脚的 de 仍然要打一拍，好与同样打了一拍的 RGB 严格对齐。
    //-------------------------------------------------------------------------
    wire de_now = (hcnt >= H_BP[15:0]) && (hcnt < (H_BP + H_ACTIVE)) &&
                  (vcnt >= V_BP[15:0]) && (vcnt < (V_BP + V_ACTIVE));

    assign de_comb = de_now;

    //-------------------------------------------------------------------------
    // 由计数器译码出 DE / HSYNC / VSYNC / frame_tick
    //
    // 注意：这三个送给引脚的都是"打一拍"的寄存器输出，不是组合逻辑直接输出。
    // 原因：图案模块的颜色也是打一拍输出的，只有两者延迟相同（都是 1 拍），
    // DE 和颜色才会严格对齐，画面才不会整体偏移。
    //-------------------------------------------------------------------------
    always @(posedge pix_clk or negedge rst_n) begin
        if (!rst_n) begin
            de         <= 1'b0;
            hsync      <= 1'b1;     // 同步信号低有效，复位时拉高 = 不激活
            vsync      <= 1'b1;
            frame_tick <= 1'b0;
        end
        else begin
            de <= de_now;

            // 行同步：低有效，落在行末的 40 拍里
            hsync <= ~((hcnt >= H_SYNC_BEG[15:0]) && (hcnt < H_SYNC_END[15:0]));

            // 场同步：低有效，落在帧末的 15 行里
            vsync <= ~((vcnt >= V_SYNC_BEG[15:0]) && (vcnt < V_SYNC_END[15:0]));

            // 一帧的最后一个像素：给上层做帧率分频/动画用
            frame_tick <= (hcnt == H_TOTAL[15:0] - 16'd1) &&
                          (vcnt == V_TOTAL[15:0] - 16'd1);
        end
    end

    // 当前坐标直接吐给图案发生器用
    assign x = hcnt;
    assign y = vcnt;

endmodule
