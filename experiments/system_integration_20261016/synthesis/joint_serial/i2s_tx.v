//=============================================================================
// i2s_tx.v —— I2S（Philips 标准）发送器
//
// 【目标器件】MAX98357A（板载 I2S 输入 DAC + D 类功放）
//   · 不需要 MCLK、不需要 I2C 配置 —— 只有 BCK / WS / DIN 三根线
//   · 支持 BCK/LRCK = 32（16 bit × 2 声道），正好对应本项目 46875 Hz 的时钟链
//   · PA_EN(引脚51) = SD_MODE，高电平使能（在顶层直接拉高即可）
//
// 【时钟关系（全部来自 audio_clk_en，单时钟域、零派生时钟）】
//   27 MHz ─┬─ bck  : 每 18 拍一个完整周期 = 1.5 MHz（引脚方波）
//           ├─ bck_en: 每 18 拍一个脉冲 = "该发下一位了"
//           ├─ lrck : 每 16 个 BCK 翻转一次 = 46875 Hz（WS 引脚）
//           └─ sample_en: 每个 LRCK 周期一拍 = 46875 Hz（新样本）
//
// 【位序与相位（这段是 I2S 最容易做错的地方，务必看懂）】
//   一个 LRCK 周期 = 32 个 BCK，在 lr_cnt 上数 0..31：
//       lr_cnt  0..15 : lrck=0（左声道），其中 lr_cnt=0 送出【左 MSB】
//       lr_cnt 16..31 : lrck=1（右声道），其中 lr_cnt=16 送出【右 MSB】
//   实现方式：一个 32 bit 移位寄存器，在 sample_en 拍装载
//                  sr <= { 左16 , 右16 }
//             在 bck_en 拍左移一位，输出恒取 sr[31]。
//   于是输出序列恰好是：左MSB..左LSB, 右MSB..右LSB —— MSB first
//
//   为什么不需要额外的"1 bit 延迟"电路：
//     I2S 规定的是【收方比发方晚一个 BCK 采样】，不是发方要把数据挪一格。
//     本项目的发方在 bck 下降沿（= bck_en 拍）改数据，收方在 bck 上升沿采样，
//     这一个半周期的错开本身就构成了那"1 bit 延迟"。
//     若再人为挪一格，反而会让整帧错位一个 bit。
//
// 【单声道 → 双声道】
//   MAX98357A 只接一只喇叭。本项目把同一个样本装进左右两个声道槽，
//   它按默认配置会把两声道混合后输出，听感与单声道一致。
//   将来换成立体声 DAC 时，只需把 sr 装载改成 {左16, 右16} 两路不同数据。
//
// 【位宽】输入 24 bit（已饱和）→ 取高 16 bit 送 DAC。
//   24→16 直接取高位是"除以 256"，不会溢出，也不会像截断那样回绕。
//=============================================================================

`timescale 1ns/1ps

module i2s_tx #(
    parameter SW = 24,      // 输入样本位宽（有符号）
    parameter DW = 16       // I2S 每声道位宽
)(
    input  wire                clk,
    input  wire                rst_n,
    // 来自 audio_clk_en 的使能/时钟
    input  wire                bck_en,
    input  wire                lrck,
    input  wire                sample_en,
    // 待发送的样本（有符号 24 bit）
    input  wire signed [SW-1:0] sample_in,
    // I2S 三线
    output wire                sd,       // 串行数据 DIN
    output wire                ws        // 字时钟 LRCK（直通 lrck）
);

    // 24 → 16：取高 16 位。有符号数取高位是"除以 256"，不会回绕。
    wire [DW-1:0] s16 = sample_in[SW-1 -: DW];

    //-------------------------------------------------------------------------
    // 32 bit 移位寄存器：{左16, 右16}，MSB first
    //   · sample_en 拍装载 → 本槽（lr_cnt=0）就输出【左 MSB】
    //   · bck_en   拍左移一位（此时 bck 引脚正在下降沿）
    //
    //   I2S 的"1 bit 延迟"到底体现在哪里（这里曾改错过一次，务必看懂）
    //   帧内槽位 k = lr_cnt（0..31），WS 在 k=0 与 k=16 翻转，数据同步在 k=0 装。
    //   看起来"WS 与 MSB 同拍"违反 I2S，其实没有：
    //     · 发送方在 bck 的【下降沿】换数据（= bck_en 那一拍）
    //     · 接收方在 bck 的【上升沿】采样（= bck_en 之后 9 拍，仍在本槽内）
    //   于是接收方看到的永远是"WS 先变、下一拍才采到 MSB"——
    //   那一个 BCK 的错开是由【收发踩不同边沿】构成的，不是靠把数据挪一格。
    //
    //   曾经试过"把装载推迟一个 bck_en"来实现这个延迟，结果是整帧错位一位：
    //   接收方收到"左 bit14..bit0 + 右 MSB"，数值变成算术右移一位（幅度减半）。
    //   实测解码值 = 源值 >> 1，一眼可辨。**不要再加那个延迟。**
    //-------------------------------------------------------------------------
    reg [2*DW-1:0] sr;

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n)
            sr <= {(2*DW){1'b0}};
        else if (sample_en)
            sr <= {s16, s16};              // 单声道：两声道填同一个样本
        else if (bck_en)
            sr <= {sr[2*DW-2:0], 1'b0};
    end

    // 输出恒取最高位 —— 装载后第一位就是左 MSB
    assign sd = sr[2*DW-1];

    // WS 直通（audio_clk_en 已经在正确的拍上翻转）
    assign ws = lrck;

endmodule
