//=============================================================================
// test_pattern.v —— 自检图案发生器（lcd_480x272 的一个"客户"）
//-----------------------------------------------------------------------------
// 画面布局（480 × 272，RGB565 = R5 / G6 / B5）：
//
//   ┌──────────────────────────────────────────────┐  ← 1 像素白色边框
//   │ 白 │ 黄 │ 青 │ 绿 │品红│ 红 │ 蓝 │ 黑 │      │  8 段标准彩条，每段 60 px
//   │    │    │    │    │    │    │    │    │      │  （全屏高度，用来验色序）
//   │    │    │    │    │    │    │    │    │      │
//   ├──────────────────────────────────────────────┤
//   │▯ ▯ ▯ ▯ ▯ ▯ ▯ ▯ ▯ ▯ ▯                │  底部 32 px：15 格二进制计数条
//   └──────────────────────────────────────────────┘    左=高位，右=低位
//
// 【三个图案各自在验证什么】（已于 2026-09-21 上板验证通过）
//   1) 彩条：验证 R/G/B 三组数据线有没有接错位、有没有某位恒 0/恒 1。
//   2) 白边框：验证有效区就是 480×272。四条边完整可见 = DE 宽度正确。
//   3) 二进制计数条：用肉眼可见的速度（约 1.7 Hz 更新）显示一个计数器的值。
//      右边几格闪得飞快（低位，肉眼看是一条灰带，属正常现象），左边几格能跟上。
//      它在动 = 帧计数器在跑 = 整个视频通路活着。
//
// 【本模块是"纯组合"的】
//   整个 (x, y) → (R, G, B) 的映射没有任何寄存器：
//   打拍、消隐全部由 lcd_480x272.v 负责（见该文件顶部的客户模块契约）。
//   只有内部状态（帧分频计数、纯色轮换计数）需要时钟。
//
// 【按键功能】mode_solid = 1 时进入纯色自检：红→绿→蓝→白 每 0.5 s 循环。
//   这一档把"某个通道完全不出光"和"颜色比例不对"区分开来。
//=============================================================================

module test_pattern #(
    // 方向诊断角标开关。
    //   1 = 在左上角画 80x60 大黑方块、右下角画 40x30 小白方块
    //   0 = 不画（正常显示用）
    // 保留这个参数是因为：屏幕方向这件事**不能靠照片判断**（手机前置摄像头会镜像、
    // 照片可能被旋转），只能靠"实物上两个不可能认错的标记"。2026-09-21 已用该方法
    // 确认方向正确，故默认关闭；将来换屏或换接线时把它打开再验一次即可。
    parameter MARKERS = 0
)(
    input  wire        pix_clk,     // 像素时钟（仅内部状态需要）
    input  wire        rst_n,
    input  wire [15:0] x,           // 行内坐标（组合）
    input  wire [15:0] y,           // 帧内行号（组合）
    input  wire        frame_tick,  // 每帧末拍一个高脉冲
    input  wire        mode_solid,  // 1 = 纯色自检模式
    output wire [4:0]  r,           // 红色分量（组合输出）
    output wire [5:0]  g,
    output wire [4:0]  b
);

    //-------------------------------------------------------------------------
    // 画面尺寸常量（必须与 lcd_480x272 的 H_ACTIVE / V_ACTIVE 一致）
    //-------------------------------------------------------------------------
    localparam [15:0] H_ACTIVE = 16'd480;
    localparam [15:0] V_ACTIVE = 16'd272;
    localparam [15:0] BAR_W    = 16'd60;   // 480 / 8 = 60 像素一段

    localparam [15:0] C_WHITE   = 16'b11111_111111_11111;
    localparam [15:0] C_YELLOW  = 16'b11111_111111_00000;
    localparam [15:0] C_CYAN    = 16'b00000_111111_11111;
    localparam [15:0] C_GREEN   = 16'b00000_111111_00000;
    localparam [15:0] C_MAGENTA = 16'b11111_000000_11111;
    localparam [15:0] C_RED     = 16'b11111_000000_00000;
    localparam [15:0] C_BLUE    = 16'b00000_000000_11111;
    localparam [15:0] C_BLACK   = 16'b00000_000000_00000;

    //-------------------------------------------------------------------------
    // 一、8 段彩条颜色（纯组合，按 x 坐标分段）
    //     写成"级联比较"而不是 x/BAR_W 除法：除以 60 不是 2 的幂，
    //     综合器会推出一个真正的除法器，既费资源又慢。比较链几乎不花代价。
    //-------------------------------------------------------------------------
    reg [15:0] bar_color;   // 打包成 {R, G, B} 方便整体搬运

    always @* begin
        if      (x < BAR_W * 1) bar_color = C_WHITE;
        else if (x < BAR_W * 2) bar_color = C_YELLOW;
        else if (x < BAR_W * 3) bar_color = C_CYAN;
        else if (x < BAR_W * 4) bar_color = C_GREEN;
        else if (x < BAR_W * 5) bar_color = C_MAGENTA;
        else if (x < BAR_W * 6) bar_color = C_RED;
        else if (x < BAR_W * 7) bar_color = C_BLUE;
        else                    bar_color = C_BLACK;
    end

    //-------------------------------------------------------------------------
    // 二、底部二进制计数条
    //     每格 32 像素宽：x[8:5] 直接就是格号（0~14），不用除法（32 = 2^5）。
    //     480 / 32 = 15 格，正好用满一行宽度。
    //-------------------------------------------------------------------------
    localparam [15:0] STRIP_TOP = V_ACTIVE - 16'd32;   // 计数条顶部 y 坐标 = 240

    reg [4:0]  div;       // 更新分频：每 32 帧更新一次显示值
    reg [14:0] shown;     // 显示出来的计数值（15 位）

    always @(posedge pix_clk or negedge rst_n) begin
        if (!rst_n) begin
            div   <= 5'd0;
            shown <= 15'd0;
        end
        else if (frame_tick) begin
            // 54 Hz 帧率 ÷ 32 ≈ 1.7 Hz，肉眼能看清最低位在跳
            if (div == 5'd31) begin
                div   <= 5'd0;
                shown <= shown + 15'd1;
            end
            else begin
                div <= div + 5'd1;
            end
        end
    end

    // 注意：变量名不能叫 cell —— cell 是 Verilog-2001 的保留字（配置块关键字），
    // 综合器会直接报 Syntax error。踩过一次，记在这里。
    wire [3:0]  cell_idx = x[8:5];                     // 格号 0(左) ~ 14(右)
    wire        bitv     = shown[4'd14 - cell_idx];    // 左边显示高位，右边显示低位
    wire        strip    = (y >= STRIP_TOP) && (y < V_ACTIVE);

    //-------------------------------------------------------------------------
    // 三、白色边框：验证有效区边界
    //-------------------------------------------------------------------------
    wire border = (x == 16'd0) || (x == H_ACTIVE - 16'd1) ||
                  (y == 16'd0) || (y == V_ACTIVE - 16'd1);

    //-------------------------------------------------------------------------
    // 三之二、方向诊断角标（默认关闭，见模块头部 MARKERS 参数说明）
    //
    // 两个方块的颜色、大小、位置三者都不同，所以四种可能的变换被唯一区分：
    //     画面正常   -> 黑在左上、白在右下
    //     水平镜像   -> 黑在右上、白在左下
    //     垂直翻转   -> 黑在左下、白在右上
    //     旋转 180°  -> 黑在右下、白在左上
    // 选这两个位置还有个原因：左上角本来是白条/黄条，黑方块在上面极显眼；
    // 右下角本来是黑条，白方块在上面同样极显眼。
    //-------------------------------------------------------------------------
    wire mark_tl = (MARKERS != 0) &&
                   (x >= 16'd8)   && (x < 16'd88)  &&      // 大黑方块 80x60
                   (y >= 16'd8)   && (y < 16'd68);
    wire mark_br = (MARKERS != 0) &&
                   (x >= 16'd424) && (x < 16'd464) &&      // 小白方块 40x30
                   (y >= 16'd196) && (y < 16'd226);

    //-------------------------------------------------------------------------
    // 四、纯色自检模式（按住按键）：红→绿→蓝→白 每 0.5 s 换一次
    //     9 MHz / 2 = 4_500_000 个时钟 = 0.5 s
    //     （这个频率常量与像素时钟绑定；若将来改 PLL，这里要跟着改）
    //-------------------------------------------------------------------------
    reg [22:0] solid_div;
    reg [1:0]  solid_idx;

    always @(posedge pix_clk or negedge rst_n) begin
        if (!rst_n) begin
            solid_div <= 23'd0;
            solid_idx <= 2'd0;
        end
        else if (mode_solid) begin
            if (solid_div == 23'd4499999) begin
                solid_div <= 23'd0;
                solid_idx <= solid_idx + 2'd1;
            end
            else begin
                solid_div <= solid_div + 23'd1;
            end
        end
        else begin
            solid_div <= 23'd0;     // 松开按键就复位，下次按下从红色开始
        end
    end

    reg [15:0] solid_color;
    always @* begin
        case (solid_idx)
            2'd0:    solid_color = C_RED;
            2'd1:    solid_color = C_GREEN;
            2'd2:    solid_color = C_BLUE;
            default: solid_color = C_WHITE;
        endcase
    end

    //-------------------------------------------------------------------------
    // 五、合成最终像素颜色（纯组合，打拍交给 lcd_480x272）
    //-------------------------------------------------------------------------
    reg [15:0] color;
    always @* begin
        if (mode_solid)   color = solid_color;                    // 纯色自检
        else if (border)  color = C_WHITE;                        // 边框
        else if (mark_tl) color = C_BLACK;                        // 方向角标：左上大黑方块
        else if (mark_br) color = C_WHITE;                        // 方向角标：右下小白方块
        else if (strip)   color = bitv ? C_WHITE : C_BLACK;       // 计数条
        else              color = bar_color;                      // 彩条
    end

    assign r = color[15:11];
    assign g = color[10:5];
    assign b = color[4:0];

endmodule
