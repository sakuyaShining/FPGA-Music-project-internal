//=============================================================================
// image_rom.v —— 图片像素 ROM（8 色索引，480×272）
//-----------------------------------------------------------------------------
// 数据来源：src/gowin/bringup_9k/image_rom.bin
//   由 tools/scripts/make_image_rom.py 从一张图片生成：
//   裁剪填满 → 加对比/饱和 → 量化到 8 色 + Floyd-Steinberg 抖动 → 每像素 3 bit
//   文件格式：每行 3 个二进制字符（000 ~ 111），共 131072 行
//
// 【为什么是 8 色、为什么这么小】
//   GW1NR-9 的 BSRAM 只有 26 块共 468 Kbit。
//   而 480×272 全彩（16 位）需要 2,088,960 bit —— 差 4.5 倍，根本放不下。
//   实测：本 ROM（131072 × 3 bit）综合后占 **24/26 块 BSRAM（93%）**，已是上限。
//   想再提高画质只能换存储介质（板载 64 Mbit PSRAM 或 32 Mbit SPI Flash），
//   那需要另写存储器控制器，属于后续工作。
//
// 【为什么深度是 131072（2^17）而不是 130560】
//   130560 正好是 480×272，但 2 的幂深度对 BSRAM 映射最友好，浪费的 512 个
//   条目只占 0.4%。多出来的部分填 0。
//
// 【初始化方式 —— 踩过的坑】
//   Gowin 综合器支持 `$readmem*`，但**文件里的数据宽度必须和存储器位宽完全一致**：
//     · 位宽 3 的存储器 用 $readmemh（十六进制，1 字符 = 4 bit）→
//       报 "WARN (EX2526): Entry size 4 ... does not match memory width 3"，
//       然后**内容被静默丢弃**（存储器虽被识别，但没有初值，整个 ROM 被优化掉，
//       资源表里 BSRAM 显示 0 块）。
//     · 改用 $readmemb（二进制，每行 3 字符）→ 正确读入。
//   另外：用来测试时**千万不要用能被地址推导出来的规律数据**（比如 mem[i] = i%8），
//   综合器会常量传播把整个 ROM 消掉，让你误以为"推断失败"。
//=============================================================================

module image_rom (
    input  wire        clk,
    input  wire [16:0] addr,    // 0 ~ 131071
    output reg  [2:0]  dout     // 8 色索引；读延迟 1 拍
);

    reg [2:0] mem [0:131071];

    initial $readmemb("image_rom.bin", mem);

    always @(posedge clk) begin
        dout <= mem[addr];
    end

endmodule
