//=============================================================================
// led_blink.v —— 最小可运行工程（跑马灯）
//
// 板卡：Tang Nano 20K  芯片：GW2AR-LV18QN88C8/I7
// 晶振：27 MHz（板载，接在引脚 4）
// LED ：5 个（引脚 19/18/17/16/15），【共阳极 → 低电平点亮】
//
// 这个文件包含了一个 FPGA 工程最核心的三件事：
//   1. 时钟        —— clk 每 1/27,000,000 秒跳变一次
//   2. 计数器      —— 数时钟个数，用来"制造时间"
//   3. 输出到引脚  —— 把状态送到 LED
//=============================================================================

module led_blink (
    input  wire       clk,      // 27 MHz 时钟输入
    output wire [4:0] led       // 5 个 LED 输出（低电平点亮）
);

    //-------------------------------------------------------------------------
    // 1) 计数器：从 0 数到 13,499,999，然后归零
    //    27 MHz ÷ 13,500,000 = 2 Hz  →  每 0.5 秒数完一轮
    //
    //    为什么是 24 位？  13,499,999 < 2^24 = 16,777,216  →  24 位够用
    //    位宽不够会溢出，数不到目标值就回绕了（这是新手最常见的 bug）
    //-------------------------------------------------------------------------
    reg [23:0] cnt;

    always @(posedge clk) begin
        if (cnt == 24'd13_499_999)
            cnt <= 24'd0;              // 数满，归零
        else
            cnt <= cnt + 1'b1;         // 否则加一
    end

    //-------------------------------------------------------------------------
    // 2) 跑马灯：每 0.5 秒把 1 的位置循环左移一位
    //    {pattern[3:0], pattern[4]} 是位拼接：把最高位移到最低位
    //
    //    注意：这里用 <= （非阻塞赋值），因为它描述的是"寄存器"
    //          同一个 always 块里不要混用 = 和 <=
    //-------------------------------------------------------------------------
    reg [4:0] pattern;

    always @(posedge clk) begin
        if (cnt == 24'd13_499_999)
            pattern <= {pattern[3:0], pattern[4]};   // 循环左移
    end

    //-------------------------------------------------------------------------
    // 3) 上电时给 pattern 一个初值，否则它可能是全 0（灯全灭）
    //    Gowin 支持用 initial 给寄存器设上电初值
    //-------------------------------------------------------------------------
    initial begin
        pattern = 5'b00001;            // 只有最低位是 1
    end

    //-------------------------------------------------------------------------
    // 4) 输出到 LED
    //    板载 LED 是【共阳极】：引脚拉低 → 电流流过 → 灯亮
    //    所以这里要取反
    //-------------------------------------------------------------------------
    assign led = ~pattern;

endmodule
