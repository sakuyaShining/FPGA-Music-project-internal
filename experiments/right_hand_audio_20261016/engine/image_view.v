//=============================================================================
// image_view.v —— 显示图片（lcd_480x272 的一个"客户"）
//-----------------------------------------------------------------------------
// 把 image_rom 里的 8 色索引像素，查表还原成 RGB565 送出去。
//
// 【关键技巧：地址预取 1 个像素，抵消 BRAM 的读延迟】
//   lcd_480x272 的客户契约要求"纯组合"：给 (x,y)，本拍就要出颜色。
//   但 BSRAM 读数据天生要 1 拍（第 t 拍给地址，第 t+1 拍出数据），做不到组合。
//
//   解法：不去取"当前像素"，而是取**下一个像素**：
//       第 t   拍：地址 = index(x+1, y)   → 第 t+1 拍数据出来 = 像素 (x+1, y)
//       第 t+1 拍：坐标正好变成 (x+1, y)  → 数据与坐标**同步到达**
//   于是对外表现就是纯组合，驱动那边一行都不用改。
//
//   行尾 (x=479) 时地址会算到下一行第 0 个像素，但下一拍坐标是 x=480（已出有效区、
//   px_de=0），会被消隐掉，不会产生可视瑕疵。
//
// 【地址计算】index = y*480 + x + 1
//   480 = 512 - 32 = (1<<9) - (1<<5)，所以 y*480 = (y<<9) - (y<<5)，
//   两次移位加一次减法就够了，**不需要乘法器**。
//   （y 在有效区内最大 271，271*480 = 130080 < 2^17，18 位足够。）
//
// 【消隐期的地址】消隐时 y 最大 296、x 最大 559，算出的地址会超过 ROM 深度。
//   这里直接把地址截断到 17 位（回绕），读到的是一段无意义的像素 ——
//   但那几拍 px_de=0，输出被驱动强制成黑色，看不见，所以无所谓。
//   好处是**不需要额外的地址比较/钳位逻辑**。
//=============================================================================

module image_view (
    input  wire        pix_clk,
    input  wire [15:0] x,          // 有效区内相对坐标 0 ~ 479
    input  wire [15:0] y,          // 有效区内相对坐标 0 ~ 271
    output wire [4:0]  r,
    output wire [5:0]  g,
    output wire [4:0]  b
);

    //-------------------------------------------------------------------------
    // 地址预取
    //-------------------------------------------------------------------------
    wire [17:0] y_times_480 = ({2'b00, y} << 9) - ({2'b00, y} << 5);
    wire [17:0] index       = y_times_480 + {2'b00, x} + 18'd1;
    wire [16:0] rom_addr    = index[16:0];      // 截断到 ROM 深度（见文件头说明）

    wire [2:0] pix_index;

    image_rom u_rom (
        .clk  (pix_clk),
        .addr (rom_addr),
        .dout (pix_index)
    );

    //-------------------------------------------------------------------------
    // 8 色调色板 → RGB565
    //   调色板由 tools/scripts/make_image_rom.py 生成，与 image_rom.bin 是同一批数据。
    //   **换图时必须同时更新这里和 .bin 文件**，否则颜色会全错。
    //-------------------------------------------------------------------------
    localparam [15:0] PAL0 = 16'hFFFF;   // RGB 248,252,248
    localparam [15:0] PAL1 = 16'hFFFD;   // RGB 248,252,232
    localparam [15:0] PAL2 = 16'hFF9C;   // RGB 248,240,224
    localparam [15:0] PAL3 = 16'hF79B;   // RGB 240,240,216
    localparam [15:0] PAL4 = 16'hF6D6;   // RGB 240,216,176
    localparam [15:0] PAL5 = 16'hCE56;   // RGB 200,200,176
    localparam [15:0] PAL6 = 16'hA50E;   // RGB 160,160,112
    localparam [15:0] PAL7 = 16'hA3A8;   // RGB 160,116, 64

    reg [15:0] color;

    always @* begin
        case (pix_index)
            3'd0:    color = PAL0;
            3'd1:    color = PAL1;
            3'd2:    color = PAL2;
            3'd3:    color = PAL3;
            3'd4:    color = PAL4;
            3'd5:    color = PAL5;
            3'd6:    color = PAL6;
            default: color = PAL7;
        endcase
    end

    assign r = color[15:11];
    assign g = color[10:5];
    assign b = color[4:0];

endmodule
