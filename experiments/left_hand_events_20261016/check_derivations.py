"""Confirm generators reproduce the tested sources and retained build inputs."""
from pathlib import Path
import hashlib,json,subprocess,sys
R=Path(__file__).resolve().parent
sha=lambda p:hashlib.sha256(p.read_bytes()).hexdigest()
files=list((R/'candidate').glob('*.v'))+[R/'rtl/left_music_probe.v',R/'rtl/instrument_owned_probe.v',R/'optimization/note_map_owned.v',R/'optimization/note_map_owned_parallel.v',R/'optimization/owner-variant.json']
for profile in ['bridge','owned_joint','owned_serial']:
    files += [p for p in (R/'synthesis'/profile).iterdir() if p.suffix in ('.v','.vh','.hex','.gprj','.tcl') or p.name=='inputs.json']
before={p.relative_to(R).as_posix():sha(p) for p in files}
for script in ['prepare_owned.py','prepare_joint.py','prepare_serial_owner.py']:
    r=subprocess.run([sys.executable,str(R/script)],cwd=R,capture_output=True,text=True)
    assert r.returncode==0,r.stderr
assert all(sha(R/name)==digest for name,digest in before.items()),'Generator changed tested source or synthesis inputs'
record=dict(status='PASS generated bytes unchanged',reason='Product probe excludes test-only compatibility wrapper so repeated preparation remains deterministic',files=before,generators={name:sha(R/name) for name in ['prepare_owned.py','prepare_joint.py','prepare_serial_owner.py']})
(R/'evidence/derivation-check.json').write_text(json.dumps(record,indent=2),encoding='utf-8')
print('PASS derivations: tested RTL and build inputs reproduced byte-for-byte')
