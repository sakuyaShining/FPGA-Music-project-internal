//=============================================================================
// led_heartbeat.v —— 板载 LED 心跳 / 计数器（bring-up 用"活体指示灯"）
//-----------------------------------------------------------------------------
// Tang Nano 9K 板载 6 颗 LED，**低电平点亮**（输出 0 = 亮，输出 1 = 灭）。
// 这一点由官方 led 例程确认：复位值 6'b111110（只有 led[0] 为 0 = 亮），
// 然后每 0.5 s 循环左移一位，形成"跑马灯"。
//
// 本模块负责其中 5 颗（led[4:0]），分工：
//   led[0]    : 每 0.5 s 翻转一次 → 1 Hz 心跳。看到它闪 = 时钟活了、逻辑在跑
//   led[4:1]  : 4 位二进制计数，每 0.5 s 加 1 → 16 步一循环的二进制跑表
//               （比单纯的闪烁信息量大：能看出计数是否连续、有没有卡住）
//
// 第 6 颗 led[5] 由顶层单独驱动，用作 PLL 锁定指示，见 bringup_top.v。
//
// 【为什么要专门做这个】
//   第一次烧录时，最怕的是"屏幕不亮，但不知道是 FPGA 没配置成功、还是屏的问题"。
//   LED 心跳独立于液晶屏工作：只要它闪，就证明①配置下载成功②时钟正常③逻辑在跑，
//   于是问题一定出在屏幕侧。这就是"可诊断性"——让每个部件都能单独自证。
//=============================================================================

module led_heartbeat #(
    parameter CLK_HZ = 27000000    // 驱动本模块的时钟频率，默认 27 MHz 板载晶振
)(
    input  wire       clk,         // 27 MHz（直接来自晶振，不经过 PLL）
    input  wire       rst_n,       // 复位，低有效（只接按键，不受 PLL 影响）
    output wire [4:0] led_lo_n     // 接到 led[4:0]，低电平点亮
);

    // 0.5 秒对应多少个时钟：27_000_000 / 2 = 13_500_000
    // 13_500_000 < 2^24 = 16_777_216，所以需要 24 位计数器（不是 23 位）
    localparam [23:0] HALF_SEC = CLK_HZ / 2;

    reg [23:0] div;     // 0.5 s 分频计数器
    reg        beat;    // 心跳位
    reg [3:0]  cnt4;    // 4 位二进制计数

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            div   <= 24'd0;
            beat  <= 1'b0;
            cnt4  <= 4'd0;
        end
        else if (div == HALF_SEC[23:0] - 24'd1) begin
            div  <= 24'd0;
            beat <= ~beat;              // 每 0.5 s 翻转 → 周期 1 s
            cnt4 <= cnt4 + 4'd1;        // 每 0.5 s 加一 → 16 步 8 秒一循环
        end
        else begin
            div <= div + 24'd1;
        end
    end

    // 注意取反：LED 低电平点亮，所以要把"逻辑 1"变成"输出 0"
    // 复位时 div/beat/cnt4 都是 0 → 输出 5'b11111 → 五颗灯全灭
    assign led_lo_n = {~cnt4, ~beat};

endmodule
