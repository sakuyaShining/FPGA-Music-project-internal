//=============================================================================
// lcd_480x272.v —— 4.3 寸 RGB 屏显示驱动（**可复用调试显示模块**）
//-----------------------------------------------------------------------------
// 板卡：Tang Nano 9K（GW1NR-LV9QN88PC6/I5）
// 屏幕：Sipeed 4.3 寸 RGB 屏，480×272，40P 排线
//
// 【它解决什么问题】
//   把"驱动一块 RGB 屏"这件事的全部脏活封在一个模块里：
//     · 27 MHz → rPLL → 像素时钟（9 MHz，见 gowin_rpll.v）
//     · PLL 未锁定前保持复位
//     · 行/场时序发生（video_timing）
//     · RGB 打一拍、消隐期强制黑色，再与 DE/HSYNC/VSYNC 严格对齐送引脚
//   上层只要把它当"一块画布"用。
//
// 【客户模块契约 —— 只有两条，越简单越不容易出错】
//   1) 组合逻辑：给当前像素坐标 (px_x, px_y)，算出这个像素的颜色 px_r/g/b。
//   2) 不用管消隐（驱动会在 px_de=0 时强制输出黑）、不用管打拍（驱动负责）。
//
//   也就是说客户模块就是一个纯组合函数：
//        (x, y) -> (R[4:0], G[5:0], B[4:0])
//
// 【为什么打拍和消隐都收在驱动里】
//   重构时踩出来的教训：如果让客户既用**寄存后的** de、又用**组合逻辑**的颜色，
//   两者会差 1 拍，有效区边缘错 1 个像素（见 video_timing.v 里 de_comb 的说明）。
//   把打拍收到一个地方，客户就只剩纯组合逻辑，这类错**从结构上不可能再发生**。
//
// 【对齐关系（想改时序的人必须看懂这一段）】
//   设 f()=有效区译码、g()=客户配色，都在第 t 拍由坐标 x(t) 决定：
//       第 t   拍：x=x(t)，px_de=f(x(t))，客户组合输出=g(x(t))
//       第 t+1 拍：引脚 lcd_r = g(x(t))，引脚 lcd_de = f(x(t))   ← 两者同源，严格对齐
//   关键点：客户必须用**组合版** px_de，不能自己去用寄存后的信号。
//
// 【像素格式】RGB565：R 5 位 + G 6 位 + B 5 位（人眼对绿色最敏感，绿色多给 1 位）
//=============================================================================

module lcd_480x272 #(
    parameter H_ACTIVE = 480,   // 一行有效像素
    parameter H_BP     = 30,    // 行后沿
    parameter H_FP     = 10,    // 行前沿
    parameter H_SYNC_W = 40,    // 行同步宽度
    parameter V_ACTIVE = 272,   // 一帧有效行
    parameter V_BP     = 5,
    parameter V_FP     = 5,
    parameter V_SYNC_W = 15
)(
    // --- 时钟与复位 ---------------------------------------------------------
    input  wire        clk_27m,     // 引脚 52：板载 27 MHz 晶振
    input  wire        rst_btn_n,   // 复位按键，按下 = 0
    output wire        pix_clk,     // 像素时钟（引出给需要同域的模块用）
    output wire        pll_locked,  // PLL 锁定指示，1 = 已锁定

    // --- 像素画布接口（接客户模块）------------------------------------------
    output wire [15:0] px_x,        // 当前像素在一行内的坐标（组合，与下面同拍）
    output wire [15:0] px_y,        // 当前行在一帧内的行号
    output wire        px_de,       // 当前像素是否在有效区内（组合，与坐标同拍）
    output wire        px_frame_tick, // 每帧最后一个像素时拉高 1 拍
    input  wire [4:0]  px_r,        // 客户给出的红色分量（组合逻辑）
    input  wire [5:0]  px_g,        // 客户给出的绿色分量
    input  wire [4:0]  px_b,        // 客户给出的蓝色分量

    // --- 物理接口（接 40P 排线）--------------------------------------------
    output wire        lcd_clk,
    output wire        lcd_de,
    output wire        lcd_hsync,
    output wire        lcd_vsync,
    output wire [4:0]  lcd_r,
    output wire [5:0]  lcd_g,
    output wire [4:0]  lcd_b
);

    //=========================================================================
    // 一、像素时钟
    //=========================================================================
    wire clk_pix;

    gowin_rpll u_pll (
        .clkout (clk_pix),
        .lock   (pll_locked),
        .clkin  (clk_27m)
    );

    assign pix_clk = clk_pix;

    //=========================================================================
    // 二、复位
    //     PLL 锁定前，它输出的是不稳定时钟，此时让逻辑跑起来可能停在任意状态。
    //     所以用 pll_locked 把复位"按住"，等时钟稳定了再放行 —— 标准做法。
    //=========================================================================
    wire rst_n = rst_btn_n & pll_locked;

    //=========================================================================
    // 三、行场时序
    //     寄存版的 de / hsync / vsync 直接从 video_timing 出来送引脚；
    //     组合版的 de_comb（与坐标同拍）留给画布接口和消隐判断。
    //     不在本模块里重抄一遍时序译码 —— 那种"同一份常量写两处"的重复，
    //     迟早会在改参数时漏改一处。
    //=========================================================================
    wire [15:0] x, y;
    wire        de_comb;

    video_timing #(
        .H_ACTIVE (H_ACTIVE), .H_BP (H_BP), .H_FP (H_FP), .H_SYNC_W (H_SYNC_W),
        .V_ACTIVE (V_ACTIVE), .V_BP (V_BP), .V_FP (V_FP), .V_SYNC_W (V_SYNC_W)
    ) u_timing (
        .pix_clk    (clk_pix),
        .rst_n      (rst_n),
        .x          (x),
        .y          (y),
        .de_comb    (de_comb),
        .de         (lcd_de),       // 寄存版：直接送引脚
        .hsync      (lcd_hsync),    // 同上，与 de 同一级寄存器，天然对齐
        .vsync      (lcd_vsync),
        .frame_tick (px_frame_tick)
    );

    // 画布接口：坐标和 de 都是组合的，与客户模块的组合同拍。
    //
    // 【重要】这里交出去的是**有效区内的相对坐标**（0 ~ H_ACTIVE-1 / 0 ~ V_ACTIVE-1），
    // 已经减掉了消隐偏移。客户模块不需要知道行场消隐有多少拍。
    //
    // 曾经踩过的坑：早先直接把计数器的值（0~H_TOTAL-1 / 0~V_TOTAL-1）当坐标交出去，
    // 于是客户以为 x=0 是屏幕左边，实际 x=0 还在行消隐里 —— 结果彩条整体右移了
    // H_BP 个像素、左边框画在消隐区里（永远看不见）、各色条宽度也不对。
    // 消隐期间坐标会下溢（无符号回绕），但那几拍 px_de=0，客户输出会被消隐掉，无影响。
    assign px_x  = x - H_BP[15:0];
    assign px_y  = y - V_BP[15:0];
    assign px_de = de_comb;

    //=========================================================================
    // 四、客户颜色 → 打一拍 → 引脚
    //     消隐期（de_comb=0）强制输出黑色，客户模块不必操心。
    //     这一级寄存器与 video_timing 里 de/hsync/vsync 的那一级是同一拍，
    //     所以引脚上的 RGB、DE、同步信号严格对齐（见文件头部的对齐关系说明）。
    //=========================================================================
    reg [4:0] r_r;
    reg [5:0] g_r;
    reg [4:0] b_r;

    always @(posedge clk_pix or negedge rst_n) begin
        if (!rst_n) begin
            r_r <= 5'd0;
            g_r <= 6'd0;
            b_r <= 5'd0;
        end
        else begin
            r_r <= de_comb ? px_r : 5'd0;
            g_r <= de_comb ? px_g : 6'd0;
            b_r <= de_comb ? px_b : 5'd0;
        end
    end

    assign lcd_r   = r_r;
    assign lcd_g   = g_r;
    assign lcd_b   = b_r;
    assign lcd_clk = clk_pix;       // 像素时钟直接由 PLL 输出引脚驱动

endmodule
